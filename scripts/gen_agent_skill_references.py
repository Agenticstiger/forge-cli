"""Generate the reference sheets of the agent skills pack from their sources.

The skills under ``fluid_build/agent_skills/skills/`` teach a coding agent the
values ``fluid validate`` accepts. Those values are not typed in by hand: they
are read from the same files the CLI reads, so a schema change that would make
a skill lie fails ``tests/agent_skills/test_reference_drift.py`` instead.

Sources:

* the newest stable bundled schema (``FluidSchemaManager.latest_bundled_version``,
  so a preview schema never leaks into the sheet),
* the vendored ODCS v3.1.0 schema, for the column-level quality operators,
* ``forge.product_types.PRODUCT_TYPES``, for the layer mapping and the
  composition rules ``fluid validate`` enforces on ``consumes[]``,
* ``_error_catalog``, for every catalogued ``ERR_*`` code and its suggestions.

Outputs are whole files (the ``references/`` sheets) and marked blocks inside a
hand-written ``SKILL.md`` (between ``<!-- BEGIN GENERATED <name> -->`` and
``<!-- END GENERATED <name> -->``), so a skill can carry a generated fact in its
body without the rest of the body becoming generated.

Usage::

    python scripts/gen_agent_skill_references.py            # (re)write the outputs
    python scripts/gen_agent_skill_references.py --check    # exit 1 if they drifted

Output is byte-stable: same sources in, same bytes out. Nothing reads the
clock, the environment or the network. The ``--check`` mode and the marker line
follow the pattern of forge_docs' ``scripts/gen_contract_reference.py``.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path
from typing import Any, Callable, Dict, Iterable, List, Mapping, Sequence

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

SKILLS_DIR = REPO_ROOT / "fluid_build" / "agent_skills" / "skills"
SCHEMAS_DIR = REPO_ROOT / "fluid_build" / "schemas"
ODCS_SCHEMA = REPO_ROOT / "fluid_build" / "providers" / "odcs" / "odcs-schema-v3.1.0.json"
DOCS_BASE = "https://agenticstiger.github.io/forge_docs"

GENERATOR = "scripts/gen_agent_skill_references.py"
_BLOCK = re.compile(
    r"(<!-- BEGIN GENERATED (?P<name>[a-z0-9-]+) -->\n)(?P<body>.*?)(<!-- END GENERATED (?P=name) -->)",
    re.S,
)


class DriftError(RuntimeError):
    """A source no longer has the shape this generator reads."""


# ---------------------------------------------------------------------------
# Schema access
# ---------------------------------------------------------------------------


def _at(node: Mapping[str, Any], *path: str) -> Any:
    """Follow ``path`` through ``node``; a missing step is a DriftError, never a default."""
    cur: Any = node
    walked: List[str] = []
    for step in path:
        walked.append(step)
        if not isinstance(cur, Mapping) or step not in cur:
            raise DriftError(f"schema has no {'/'.join(walked)}")
        cur = cur[step]
    return cur


def _enum(node: Mapping[str, Any], *path: str) -> List[Any]:
    """The ``enum`` at ``path``, looking inside one level of ``anyOf`` when needed."""
    target = _at(node, *path) if path else node
    if "enum" in target:
        return list(target["enum"])
    for alt in target.get("anyOf", []):
        if "enum" in alt:
            return list(alt["enum"])
    raise DriftError(f"no enum at {'/'.join(path)}")


def _code_list(values: Iterable[Any]) -> str:
    return ", ".join(f"`{v}`" for v in values)


def _props(node: Mapping[str, Any]) -> List[str]:
    return list(_at(node, "properties").keys())


def _stable_version() -> str:
    from fluid_build.schema_manager import FluidSchemaManager

    return FluidSchemaManager.latest_bundled_version()


def _load_schema(version: str) -> Dict[str, Any]:
    path = SCHEMAS_DIR / f"fluid-schema-{version}.json"
    return json.loads(path.read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# Renderers
# ---------------------------------------------------------------------------


def _marker(source: str) -> str:
    return f"<!-- GENERATED by {GENERATOR} from {source}; do not edit by hand. -->"


def render_contract_schema(schema: Mapping[str, Any], version: str, odcs: Mapping[str, Any]) -> str:
    """The values a contract may take, as a compressed sheet an agent can scan."""
    defs = _at(schema, "$defs")
    top = _at(schema, "properties")
    meta = _at(top, "metadata")
    owner = _at(meta, "properties", "owner")
    expose = _at(defs, "expose")
    binding = _at(defs, "binding")
    column = _at(defs, "column")
    col_quality = _at(column, "properties", "quality", "items")
    dq_rule = _at(defs, "dqRule")
    inline_quality = _at(defs, "exposeContract", "properties", "quality", "items")
    build = _at(defs, "build")
    trigger = _at(defs, "trigger")
    runtime = _at(defs, "runtime")
    consume = _at(defs, "consumeRef")
    operators = [
        next(iter(_at(alt, "properties")))
        for alt in _at(odcs, "$defs", "DataQualityOperators", "oneOf")
    ]
    ident = _at(defs, "identifier", "pattern")

    lines = [
        _marker(f"fluid_build/schemas/fluid-schema-{version}.json"),
        "",
        f"# FLUID contract cheat sheet (schema {version})",
        "",
        "The values `fluid validate` accepts, read from the schema it checks an untagged",
        "contract against. Anything not listed here is either free text or refused.",
        f"Full field reference: {DOCS_BASE}/reference/contract-{version}.html",
        "",
        "## Top level",
        "",
        f"- Required: {_code_list(_at(schema, 'required'))}.",
        f"- `fluidVersion`: {_code_list(_enum(top, 'fluidVersion'))}. Write `{version}`.",
        f"- `kind`: {_code_list(_enum(top, 'kind'))}.",
        f"- All keys: {_code_list(top.keys())}.",
        f"- Ids (`id`, `exposeId`, build `id`, `productId`) match `{ident}`.",
        "",
        "## metadata",
        "",
        f"- Required: {_code_list(_at(meta, 'required'))}.",
        f"- `owner` keys (none required): {_code_list(_props(owner))}.",
        f"- `productType`: {_code_list(_enum(meta, 'properties', 'productType'))}.",
        "- `layer` is free text; with `productType` set it must be the canonical pair:",
        "  " + ", ".join(f"`{pt.layer}` = `{pt.code}`" for pt in _product_types()) + ".",
        f"- `classification`: {_code_list(_enum(meta, 'properties', 'classification'))}.",
        "",
        "## exposes[]",
        "",
        f"- Required: {_code_list(_at(expose, 'required'))}.",
        f"- `kind`: {_code_list(_enum(expose, 'properties', 'kind'))}.",
        f"- `binding` required: {_code_list(_at(binding, 'required'))}.",
        f"- `binding.platform`: {_code_list(_enum(binding, 'properties', 'platform'))}.",
        f"- `binding.format`: {_code_list(_enum(binding, 'properties', 'format'))}.",
        "- `binding.location` keys (none required, no others allowed): "
        + _code_list(_props(_at(defs, "bindingLocation")))
        + ".",
        "",
        "### Columns: `exposes[].contract.schema[]`",
        "",
        f"- Required: {_code_list(_at(column, 'required'))}. Keys: {_code_list(_props(column))}.",
        "- `type` (case-insensitive; parameterised forms such as `decimal(18,4)` and",
        f"  `varchar(255)` are accepted): {_code_list(_enum(column, 'properties', 'type'))}.",
        f"- `sensitivity`: {_code_list(_enum(_at(defs, 'sensitivityLevel')))}.",
        "",
        "### Quality rules",
        "",
        "- `exposes[].contract.dq.rules[]` is what the quality engine runs.",
        f"  Required: {_code_list(_at(dq_rule, 'required'))}.",
        f"  `type`: {_code_list(_enum(dq_rule, 'properties', 'type'))}.",
        f"  `operator`: {_code_list(_enum(dq_rule, 'properties', 'operator'))}.",
        f"  `severity`: {_code_list(_enum(dq_rule, 'properties', 'severity'))}.",
        "  `selector` names the column; `threshold` is a number; `window` is an ISO-8601",
        "  duration such as `P1D`.",
        "- `exposes[].contract.schema[].quality[]` is the ODCS v3.1.0 shape, exported as-is.",
        f"  `type`: {_code_list(_enum(col_quality, 'properties', 'type'))}.",
        f"  Library `metric`: {_code_list(_enum(col_quality, 'properties', 'metric'))}.",
        f"  Comparison (exactly one): {_code_list(operators)}.",
        f"  `dimension`: {_code_list(_enum(col_quality, 'properties', 'dimension'))}.",
        "- `exposes[].contract.quality[]` is an inline SQL assertion.",
        f"  Required: {_code_list(_at(inline_quality, 'required'))}.",
        f"  `severity`: {_code_list(_enum(inline_quality, 'properties', 'severity'))}.",
        "",
        "## builds[]",
        "",
        f"- `pattern`: {_code_list(_enum(build, 'properties', 'pattern'))}.",
        f"- `engine`: {_code_list(_enum(build, 'properties', 'engine'))}.",
        f"- `execution.trigger.type`: {_code_list(_enum(trigger, 'properties', 'type'))}.",
        "  A `schedule` trigger takes a five-field `cron`, for example `0 2 * * *`.",
        f"- `execution.runtime.platform`: {_code_list(_enum(runtime, 'properties', 'platform'))}.",
        "",
        "## consumes[]",
        "",
        f"- Required: {_code_list(_at(consume, 'required'))}. `productId` is the upstream",
        "  contract's `id`; `exposeId` is one of its `exposes[].exposeId`.",
        f"- Keys: {_code_list(_props(consume))}.",
        "",
    ]
    return "\n".join(lines)


def render_error_codes() -> str:
    """Every catalogued ``ERR_*`` code with the advice the CLI prints for it."""
    from fluid_build import _error_catalog as catalog

    base = catalog.DOC_BASE.rstrip("/") + "/"
    rows = []
    for event in catalog.catalogued_events():
        tips = " ".join(_md_cell(s.rstrip(".")) + "." for s in catalog.suggestions_for(event))
        url = catalog.docs_url_for(event)
        page = url[len(base) :] if url.startswith(base) else url
        rows.append(f"| `{catalog.slug_for(event)}` | {tips} | {page} |")
    lines = [
        _marker("fluid_build/_error_catalog.py"),
        "",
        "# fluid error codes",
        "",
        "Every failure prints a stable `ERR_<EVENT>` code next to its message. Find the",
        "code here and do what the first suggestion says, then re-run the command. A code",
        "missing from this table has no curated advice: read the message it printed.",
        "`fluid validate --format json` gives every finding in a contract as an entry of",
        "`issues`, with its code, a JSON `pointer` to the place, a `fix` and an `example`:",
        "the `ERR_CONTRACT_*` codes below.",
        f"Docs pages are relative to {base}",
        "",
        "| Code | What to do | Docs page |",
        "|---|---|---|",
        *rows,
        "",
    ]
    return "\n".join(lines)


def _md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_composition_block() -> str:
    """The ``consumes[]`` rules ``fluid validate`` enforces, by product type."""
    lines = ["| productType | layer | may consume |", "|---|---|---|"]
    for pt in _product_types():
        allowed = sorted(pt.allowed_upstream_types)
        lines.append(
            f"| `{pt.code}` | `{pt.layer}` | "
            + (", ".join(f"`{a}`" for a in allowed) if allowed else "nothing (no `consumes[]`)")
            + " |"
        )
    return "\n".join(lines) + "\n"


def _product_types() -> Sequence[Any]:
    from fluid_build.forge.product_types import PRODUCT_TYPES

    return PRODUCT_TYPES


# ---------------------------------------------------------------------------
# Output plan
# ---------------------------------------------------------------------------

#: Marked blocks, by name. A SKILL.md may carry any of them.
BLOCKS: Dict[str, Callable[[], str]] = {
    "composition-rules": render_composition_block,
}


def whole_files() -> Dict[Path, str]:
    """Every generated file, by path, with the bytes it must hold."""
    version = _stable_version()
    schema = _load_schema(version)
    odcs = json.loads(ODCS_SCHEMA.read_text(encoding="utf-8"))
    return {
        SKILLS_DIR
        / "authoring-fluid-contracts"
        / "references"
        / "contract-schema.md": render_contract_schema(schema, version, odcs),
        SKILLS_DIR
        / "troubleshooting-fluid-errors"
        / "references"
        / "error-codes.md": (render_error_codes()),
    }


def fill_blocks(text: str) -> str:
    """Rewrite every marked block in ``text``; an unknown block name is a DriftError."""

    def _sub(match: "re.Match[str]") -> str:
        name = match.group("name")
        if name not in BLOCKS:
            raise DriftError(f"unknown generated block {name!r}")
        return match.group(1) + BLOCKS[name]() + match.group(4)

    return _BLOCK.sub(_sub, text)


def expected_outputs() -> Dict[Path, str]:
    """Whole files plus every SKILL.md with its blocks filled in."""
    out = whole_files()
    for skill_md in sorted(SKILLS_DIR.glob("*/SKILL.md")):
        current = skill_md.read_text(encoding="utf-8")
        filled = fill_blocks(current)
        if filled != current or _BLOCK.search(current):
            out[skill_md] = filled
    return out


def _display(path: Path) -> str:
    try:
        return path.relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return str(path)


def check() -> List[str]:
    """Unified diffs for every output that differs from what would be generated."""
    problems = []
    for path, expected in sorted(expected_outputs().items()):
        actual = path.read_text(encoding="utf-8") if path.exists() else ""
        if actual != expected:
            rel = _display(path)
            diff = difflib.unified_diff(
                actual.splitlines(keepends=True),
                expected.splitlines(keepends=True),
                fromfile=f"{rel} (committed)",
                tofile=f"{rel} (generated)",
            )
            problems.append("".join(diff) or f"{rel}: missing")
    return problems


def write() -> List[Path]:
    written = []
    for path, expected in sorted(expected_outputs().items()):
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
            written.append(path)
    return written


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if an output drifted")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for problem in problems:
            print(problem)
        if problems:
            print(f"{len(problems)} output(s) drifted: run python {GENERATOR}", file=sys.stderr)
            return 1
        print("agent skill references are up to date")
        return 0
    for path in write():
        print(f"wrote {_display(path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
