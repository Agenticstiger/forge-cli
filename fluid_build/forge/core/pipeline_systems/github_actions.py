"""GitHubActionsTemplate: the thin ``fluid ship`` workflow for GitHub Actions.

One workflow, two jobs. ``plan`` runs stages 1-6 on a pull request, on a push
to the default branch and on a manual run, and keeps ``runtime/`` and
``dist/artifacts/`` as the ``fluid-runtime`` artifact. ``apply`` runs stages
7-11 after it, on a push to the default branch or a manual run, in the GitHub
environment named after ``FLUID_ENV``, whose protection rules can require a
reviewer before it starts. Each stage is one step running
``fluid ship --stage N``: a ``RUN_STAGE_<N>_<NAME>`` of ``false`` hides the
step, and ship skips the stage too.

Values reach ship through ``env:`` only: a manual run's input when one is
given (a box always is), else the repository or environment variable, else the
generated default. None is expanded inside a ``run:`` script, where it would be
code. The install variables are never inputs: whoever starts a run could
otherwise choose the package the apply job runs.
"""

from __future__ import annotations

from typing import Any, Dict, List, Tuple

from . import _keyless, _thin
from ._base import BasePipelineTemplate, PipelineConfig, _pin_action, check_pipeline_workdir

WORKFLOW_PATH = ".github/workflows/fluid-pipeline.yml"
RUNTIME_ARTIFACT = "fluid-runtime"
REPORTS_ARTIFACT = "fluid-reports"
#: GitHub's limit on a workflow_dispatch's inputs.
MAX_DISPATCH_INPUTS = 25

#: Read from repository or environment variables only, never asked on a
#: manual run (the 25-input limit): the install knobs. The contract path is
#: written into the steps.
_VARIABLE_ONLY: Tuple[str, ...] = ("CONTRACT", *_thin.INSTALL_VARIABLES)

#: A choice input's value for "not chosen here": the variable, else the default.
_FROM_VARIABLE = "default"
#: The stage knobs ship reads, each with its own default when unset.
STAGE_KNOBS: Tuple[str, ...] = (
    "VALIDATE_STRICT",
    "VERIFY_STRICT",
    "GENERATE_EMIT",
    "DIFF_EXIT_ON_DRIFT",
    "DIFF_LAST_APPLIED",
    "PLAN_HTML",
    "POLICY_APPLY_MODE",
)


def _or_default(default: str) -> str:
    """`` || '<default>'`` for an expression, or nothing for a blank default.
    The default is a checked literal (no quote can end the string)."""
    return f" || '{default}'" if default else ""


class GitHubActionsTemplate(BasePipelineTemplate):
    """GitHub Actions pipeline template"""

    def __init__(self) -> None:
        super().__init__()
        self.provider_name = "GitHub Actions"
        self.file_extensions = [".yml", ".yaml"]

    def generate(self, config: PipelineConfig) -> Dict[str, str]:
        workflow = self._workflow(config)
        files = {WORKFLOW_PATH: self._header(config) + _thin.render_yaml(workflow)}
        for add_on in _thin.check_add_ons(config.add_ons):
            path, document = self._add_on(add_on, config)
            note = (
                f"# fluid {_thin.ADD_ON_TITLES[add_on]}, generated by "
                f"`fluid generate ci --system github --add {add_on}`.\n\n"
            )
            files[path] = note + _thin.render_yaml(document)
        return files

    # ------------------------------------------------------------------
    # Add-ons: the jobs the retired advanced and enterprise tiers carried
    # ------------------------------------------------------------------

    def _add_on(self, add_on: str, config: PipelineConfig) -> Tuple[str, Dict[str, Any]]:
        branch = self._branch(config)
        contract = config.contract_path or _thin.DEFAULT_CONTRACT
        target = _thin.quoted_contract(contract)
        base = self._job_base(config, _thin.ADD_ON_TITLES[add_on])
        if add_on == "security":
            base["permissions"] = {"contents": "read", "security-events": "write"}
            base.pop("env", None)
            base["steps"] = [
                *self._setup_steps(config),
                {
                    # Advisory: findings reach code scanning, they do not fail the job.
                    "name": "Scan the dependencies (OSV-Scanner)",
                    "uses": _pin_action("google/osv-scanner-action/osv-scanner-action@v2"),
                    "continue-on-error": True,
                    "with": {
                        "scan-args": _keyless.LiteralStr(
                            "--format=sarif\n--output=osv-results.sarif\n--recursive\n./\n"
                        )
                    },
                },
                {
                    "name": "Check the contract's policies",
                    "run": f"fluid policy-check {target} --strict",
                },
                {
                    "name": "Upload the scan to code scanning",
                    "if": "always()",
                    "uses": _pin_action("github/codeql-action/upload-sarif@v3"),
                    "with": {"sarif_file": "osv-results.sarif"},
                },
            ]
            on: Dict[str, Any] = {
                "pull_request": {"branches": [branch]},
                "push": {"branches": [branch]},
                "schedule": [{"cron": "0 2 * * *"}],
                "workflow_dispatch": None,
            }
            return ".github/workflows/fluid-security.yml", self._add_on_workflow(add_on, on, base)
        if add_on == "compliance":
            base["steps"] = [
                *self._setup_steps(config),
                # `fluid verify` reconciles lineage against the deployed target.
                *_keyless.github_auth_steps(config.cloud_auth, _pin_action),
                {
                    "name": "Write the compliance report",
                    "run": (
                        "mkdir -p runtime && fluid policy-check "
                        f"{target} --format json --output runtime/compliance-report.json"
                    ),
                },
                {
                    "name": "Check the data lineage",
                    "run": f"fluid verify {target} --reconcile-lineage --warn-only",
                },
                {
                    "name": "Keep the compliance report",
                    "if": "always()",
                    "uses": _pin_action("actions/upload-artifact@v4"),
                    "with": {
                        "name": "fluid-compliance",
                        "path": self._in_workdir(config, "runtime/compliance-report.json"),
                    },
                },
            ]
            on = {"schedule": [{"cron": "0 0 * * 0"}], "workflow_dispatch": None}
            return ".github/workflows/fluid-compliance.yml", self._add_on_workflow(add_on, on, base)
        # sbom
        base["permissions"] = {"contents": "read", "id-token": "write", "attestations": "write"}
        base.pop("env", None)
        base.pop("defaults", None)
        base["steps"] = [
            {
                "name": "Checkout",
                "uses": _pin_action("actions/checkout@v4"),
                "with": {"persist-credentials": False},
            },
            {
                "name": "Write the SBOM",
                "uses": _pin_action("anchore/sbom-action@v0"),
                "with": {"output-file": "sbom.spdx.json"},
            },
            {
                "name": "Attest it",
                "uses": _pin_action("actions/attest-build-provenance@v2"),
                "with": {"subject-path": "sbom.spdx.json"},
            },
            {
                "name": "Keep the SBOM",
                "uses": _pin_action("actions/upload-artifact@v4"),
                "with": {"name": "sbom", "path": "sbom.spdx.json"},
            },
        ]
        on = {"schedule": [{"cron": "0 0 * * 0"}], "workflow_dispatch": None}
        return ".github/workflows/fluid-sbom.yml", self._add_on_workflow(add_on, on, base)

    @staticmethod
    def _add_on_workflow(add_on: str, on: Dict[str, Any], job: Dict[str, Any]) -> Dict[str, Any]:
        return {
            "name": f"fluid {_thin.ADD_ON_TITLES[add_on]}",
            "on": on,
            "permissions": {},
            "jobs": {add_on: job},
        }

    # ------------------------------------------------------------------
    # The workflow
    # ------------------------------------------------------------------

    def _workflow(self, config: PipelineConfig) -> Dict[str, Any]:
        params = self._eleven_stage_parameters(config)
        branch = self._branch(config)
        return {
            "name": "fluid pipeline",
            "on": {
                "pull_request": {"branches": [branch]},
                "push": {"branches": [branch]},
                "workflow_dispatch": {"inputs": self._inputs(params)},
            },
            "permissions": {},
            # A newer push to a pull request replaces its run; a push to the
            # default branch waits for the one before it, never cancels it.
            "concurrency": {
                "group": "fluid-pipeline-${{ github.ref }}",
                "cancel-in-progress": "${{ github.event_name == 'pull_request' }}",
            },
            "env": self._env(config, params),
            "jobs": {
                "plan": self._plan_job(config),
                "apply": self._apply_job(config, branch),
            },
        }

    @staticmethod
    def _branch(config: PipelineConfig) -> str:
        return config.default_branch  # checked by PipelineConfig

    @staticmethod
    def _inputs(params: List[Tuple[str, str, str, str]]) -> Dict[str, Any]:
        """A manual run's inputs: every parameter but the variable-only ones."""
        inputs: Dict[str, Any] = {}
        for name, kind, default, description in params:
            if name in _VARIABLE_ONLY:
                continue
            key = name.lower()
            # Left blank (or "default"), an input takes the repository or
            # environment variable of the same name, else the generated default,
            # as a push or pull request run does. A box is ticked or not: on a
            # manual run it decides.
            fallback = f"Blank: vars.{name}, else {default or 'blank'}."
            options = kind.split(":", 1)[1].split(",") if kind.startswith("choice:") else []
            if options and "" in options:
                # GitHub refuses a blank choice option, and blank is a value
                # here (SCHEDULER: none): a string input naming the choices.
                named = ", ".join(o for o in options if o)
                inputs[key] = {
                    "description": f"{description} One of: {named}. {fallback}",
                    "type": "string",
                    "default": "",
                }
            elif options:
                inputs[key] = {
                    "description": (
                        f"{description} {_FROM_VARIABLE}: vars.{name}, else {default}."
                    ),
                    "type": "choice",
                    "options": [_FROM_VARIABLE, *options],
                    "default": _FROM_VARIABLE,
                }
            elif kind == "boolean":
                inputs[key] = {
                    "description": description,
                    "type": "boolean",
                    "default": default == "true",
                }
            else:
                inputs[key] = {
                    "description": f"{description} {fallback}",
                    "type": "string",
                    "default": "",
                }
        if len(inputs) > MAX_DISPATCH_INPUTS:
            raise ValueError(
                f"{len(inputs)} workflow_dispatch inputs; GitHub allows {MAX_DISPATCH_INPUTS}"
            )
        return inputs

    def _env(
        self, config: PipelineConfig, params: List[Tuple[str, str, str, str]]
    ) -> Dict[str, str]:
        """What every step reads: input, else variable, else the default.

        ``format('{0}', inputs.x)`` turns a boolean input into ``'true'`` or
        ``'false'``; a plain ``inputs.x || ...`` would read an unchecked box
        as missing and take the variable instead."""
        env: Dict[str, str] = {
            # One run id for both jobs, so their stages share one ship report.
            "FLUID_RUN_ID": "${{ github.run_id }}-${{ github.run_attempt }}",
        }
        for name, kind, default, _ in params:
            if name == "CONTRACT":
                continue
            key = name.lower()
            if name in _VARIABLE_ONLY:
                value = f"vars.{name}{_or_default(default)}"
            elif kind == "boolean":
                value = (
                    f"github.event_name == 'workflow_dispatch' && format('{{0}}', inputs.{key})"
                    f" || vars.{name}{_or_default(default)}"
                )
            else:
                chosen = f"inputs.{key}"
                if kind.startswith("choice:") and "" not in kind.split(":", 1)[1].split(","):
                    chosen = f"(inputs.{key} != '{_FROM_VARIABLE}' && inputs.{key})"
                value = f"{chosen} || vars.{name}{_or_default(default)}"
            env[name] = "${{ " + value + " }}"
        for knob in STAGE_KNOBS:
            env[knob] = "${{ vars." + knob + " }}"
        env.update(self._engine_runtime_env_vars(config))
        return env

    def _job_base(self, config: PipelineConfig, name: str) -> Dict[str, Any]:
        job: Dict[str, Any] = {
            "name": name,
            "runs-on": "ubuntu-latest",
            # contents: read, plus id-token: write when the contract binds a
            # cloud: stage 5 reads the target, stage 7 on change it.
            "permissions": _keyless.github_job_permissions(config.cloud_auth),
        }
        auth_env = _keyless.github_auth_env(config.cloud_auth)
        if auth_env:
            job["env"] = auth_env
        if config.workdir:
            job["defaults"] = {"run": {"working-directory": check_pipeline_workdir(config.workdir)}}
        return job

    def _setup_steps(self, config: PipelineConfig) -> List[Dict[str, Any]]:
        return [
            {
                "name": "Checkout",
                "uses": _pin_action("actions/checkout@v4"),
                # The token stays out of .git/config, where a later step could read it.
                "with": {"persist-credentials": False},
            },
            {
                "name": "Set up Python",
                "uses": _pin_action("actions/setup-python@v5"),
                "with": {"python-version": "3.12"},
            },
            {
                "name": "Install fluid",
                "run": _keyless.LiteralStr(self._render_install_setup(config) + "\n"),
                "shell": "bash",
            },
        ]

    def _stage_steps(
        self, config: PipelineConfig, numbers: Tuple[int, ...]
    ) -> List[Dict[str, Any]]:
        steps = []
        for stage in _thin.phase(numbers):
            if stage.opt_in:
                condition = f"env.{stage.toggle} == 'true'"
            else:
                condition = f"env.{stage.toggle} != 'false'"
            steps.append(
                {
                    "name": stage.title,
                    "if": condition,
                    "run": stage.command(config.contract_path or _thin.DEFAULT_CONTRACT),
                }
            )
        return steps

    @staticmethod
    def _in_workdir(config: PipelineConfig, path: str) -> str:
        return f"{config.workdir.rstrip('/')}/{path}" if config.workdir else path

    def _carried(self, config: PipelineConfig) -> str:
        return "\n".join(self._in_workdir(config, p) for p in _thin.CARRIED_PATHS) + "\n"

    def _plan_job(self, config: PipelineConfig) -> Dict[str, Any]:
        job = self._job_base(config, "plan (stages 1-6)")
        job["steps"] = [
            *self._setup_steps(config),
            *_keyless.github_auth_steps(config.cloud_auth, _pin_action),
            *self._stage_steps(config, _thin.PLAN_STAGES),
            {
                # The reviewed plan, the frozen bundle and the stage reports:
                # what apply runs, and what a reviewer reads on a pull request.
                "name": "Keep the bundle, plan and reports",
                "if": "always()",
                "uses": _pin_action("actions/upload-artifact@v4"),
                "with": {
                    "name": RUNTIME_ARTIFACT,
                    "path": _keyless.LiteralStr(self._carried(config)),
                    "overwrite": True,
                },
            },
        ]
        return job

    def _apply_job(self, config: PipelineConfig, branch: str) -> Dict[str, Any]:
        env_name = "inputs.fluid_env || vars.FLUID_ENV" + _or_default(
            self._pipeline_defaults(config)["FLUID_ENV"]
        )
        job = self._job_base(config, "apply (stages 7-11)")
        job.update(
            {
                "needs": "plan",
                "if": (
                    "github.event_name == 'workflow_dispatch' || "
                    f"(github.event_name == 'push' && github.ref == 'refs/heads/{branch}')"
                ),
                # Its protection rules (required reviewers, a wait timer, the
                # branches that may deploy) gate stages 7-11.
                "environment": "${{ " + env_name + " }}",
                # One apply per environment at a time; a second one waits.
                "concurrency": {
                    "group": "fluid-apply-${{ " + env_name + " }}",
                    "cancel-in-progress": False,
                },
            }
        )
        job["steps"] = [
            *self._setup_steps(config),
            {
                "name": "Fetch the bundle and plan the plan job kept",
                "uses": _pin_action("actions/download-artifact@v4"),
                "with": {"name": RUNTIME_ARTIFACT, "path": config.workdir or "."},
            },
            *_keyless.github_auth_steps(config.cloud_auth, _pin_action),
            *self._stage_steps(config, _thin.APPLY_STAGES),
            {
                "name": "Keep the apply reports",
                "if": "always()",
                "uses": _pin_action("actions/upload-artifact@v4"),
                "with": {
                    "name": REPORTS_ARTIFACT,
                    "path": _keyless.LiteralStr(self._carried(config)),
                    "overwrite": True,
                },
            },
        ]
        return job

    def _header(self, config: PipelineConfig) -> str:
        branch = self._branch(config)
        env_default = self._pipeline_defaults(config)["FLUID_ENV"]
        lines = [
            "fluid pipeline, generated by `fluid generate ci --system github`.",
            "Every stage is one step running `fluid ship --stage N` (see `fluid ship --help`).",
            "",
            f"A pull request against {branch} runs stages 1-6 (plan) and keeps runtime/ as",
            f"the {RUNTIME_ARTIFACT} artifact. A push to {branch} also runs stages 7-11 (apply)",
            "in the GitHub environment named after FLUID_ENV (default "
            f"{env_default}): give it required",
            "reviewers (Settings > Environments) so nothing is applied unreviewed.",
            "",
            "Each value comes from a repository or environment variable of the same",
            "name, else the default written below: FLUID_ENV, APPLY_MODE,",
            "RUN_STAGE_<N>_<NAME>, " + ", ".join(STAGE_KNOBS[:3]) + ",",
            ", ".join(STAGE_KNOBS[3:]) + ".",
            "A manual run (Actions > fluid pipeline > Run workflow) can set most of them;",
            "a blank input (or `default`) keeps the variable, and a box decides.",
            "FLUID_PACKAGE_SPEC and the FLUID_PIP_* install variables are variables only:",
            "whoever starts a run could otherwise choose the package apply runs.",
            "",
            "A pull request from a fork gets no ID token, so its stages 5 and 6 cannot",
            "reach the cloud.",
        ]
        header = "".join(f"# {line}".rstrip() + "\n" for line in lines) + "\n"
        banner = self._credential_banner(
            comment_prefix="# ",
            ci_system_name="GitHub Actions",
            secret_surface_hint=(
                "Settings > Secrets and variables > Actions. "
                "Map each secret to a job-level env: block."
            ),
            cloud_auth=config.cloud_auth,
        )
        notes = self._engine_runtime_notes(config)
        return header + banner + (notes + "\n" if notes else "")
