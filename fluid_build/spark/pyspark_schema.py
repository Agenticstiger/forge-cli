#: The first line of every generated module. A file that starts with it was written by this
#: command and is replaced when the contract changes; any other file is never overwritten.
HEADER = "# Generated by `fluid generate pyspark-schema`. Do not edit: regenerate."

#: The second line. The interpreter reads an encoding declaration from line 1 or line 2, so
#: both are fixed text and no contract value is ever written on them.
CODING = "# -*- coding: utf-8 -*-"

#: The comment that names the data product a module was generated for. It comes after the
#: fixed lines (an editor reads its modelines from the first five), and ``orphans`` tells one
#: contract's modules from another's by it.
PRODUCT_PREFIX = "# data product: "

#: What a module's file name ends with: ``orders_schema.py``. A bare ``orders.py`` could shadow
#: a standard library module (``types``, ``json``) once the directory is on ``sys.path``, which
#: ``spark-submit --py-files`` does.
SUFFIX = "_schema"

#: How deeply a column may nest structs, arrays and maps.
MAX_DEPTH = 32

# The most characters of a port's identifier a file name keeps (255 bytes is the usual limit);
# a longer one is cut and ends in a hash of the whole.
_MAX_NAME = 80

# A one-line call longer than this is written one argument to a line.
_WIDTH = 88
# The longest column description kept as a comment above its field.
_COMMENT_WIDTH = 80

# Keys a column declares its nested types with.
_NESTED_KEYS = frozenset({"fields", "element", "key", "value"})
_STRUCT_NAMES = frozenset({"struct", "object", "record", "row"})

# FLUID column type, keyed on the lower-cased base name (``varchar(255)`` is ``varchar``), to the
# Spark type it is written as. Only a type Spark holds without loss is here; ``_scalar``
# classifies every other one, and judges the Glue emitter's table the same way
# (``iac/providers/aws.py``), so one contract reads alike through Glue and Spark.
#
# Where the choice is not obvious: ``char`` and ``varchar`` are ``StringType()`` because a
# DataFrame cannot hold ``CharType`` or ``VarcharType`` (Spark's migration guide: table schemas
# only), so the length is a quality check, not a type; the ``timestamp`` family that carries a
# zone is ``TimestampType()``, an instant, and the one that does not is
# ``TimestampNTZType()`` (Spark 3.3 and later); ``money`` is SQL Server's ``decimal(19,4)``;
# ``year`` is MySQL's four-digit number, so ``smallint``; ``bit`` is the SQL Server 0/1 flag.
_SPARK_TYPES = column_types.expand(
    {
        "StringType()": "string, str, text, varchar, varchar2, nvarchar, char, nchar, character, "
        "clob, uuid, uniqueidentifier, guid, enum",
        "ByteType()": "tinyint",
        "ShortType()": "smallint, int2, int16, year",
        "IntegerType()": "int, integer, int4, int32, mediumint, serial",
        "LongType()": "bigint, int8, int64, long, longint, bigserial",
        "FloatType()": "float, float4, float32, real",
        "DoubleType()": "double, double precision, float8, float64",
        "BooleanType()": "boolean, bool, bit",
        "DateType()": "date",
        "TimestampType()": "timestamp, datetime, datetime2, smalldatetime, timestamptz, "
        "timestamp_tz, timestamp_ltz, timestamp with time zone",
        "TimestampNTZType()": "timestamp_ntz, timestampntz, timestamp without time zone",
        "BinaryType()": "binary, bytes, varbinary, blob, bytea, raw",
        "DecimalType(19, 4)": "money",
    }
)

# Types Spark has no portable form for but whose value survives as text: written as
# ``StringType()``, and the caller warns.
_AS_STRING = {
    "json": "which Spark has no json type for",
    "jsonb": "which Spark has no jsonb type for",
    "variant": "whose VariantType needs Spark 4.0, so a portable schema holds it as text",
    "super": "which Spark has no super type for",
    "time": "which Spark has no time-of-day type for",
    "interval": "which Spark has no single interval type for (year-month and day-time differ)",
    "bignumeric": "whose digits beyond 38 no Spark decimal holds",
}

# Types with no Spark form and no fallback worth writing: which encoding a spatial value or a
# sketch takes is the writer's, and a guess would be wrong half the time.
_REFUSED = {
    **{
        t: (
            "which has no Spark column type (a spatial value is stored as WKT text or WKB "
            "bytes, and only the writer knows which)",
            "Declare string (WKT) or binary (WKB), whichever the data holds.",
        )
        for t in ("geography", "geometry", "geom", "point")
    },
    "hll": (
        "which is an engine-specific sketch with no Spark column type",
        "Declare binary to store the sketch's bytes.",
    ),
}

_DECIMAL_FAMILY = frozenset({"decimal", "numeric", "dec", "number"})
# ASCII digits only: ``\d`` alone also matches Arabic-Indic and other Unicode digits.
_DECIMAL_ARGS_RE = re.compile(r"\((\d{1,9})(?:,(\d{1,9}))?\)", re.ASCII)
# What a bare ``decimal`` is: the Glue emitter's default, wider than Spark's own (10,0) so a
# fraction is never cut.
_DECIMAL_DEFAULT = "DecimalType(38, 9)"
_TYPE_FIX = (
    "Declare a FLUID column type such as string, integer, bigint, decimal(12,2), double, "
    "boolean, date or timestamp."
)
_NESTED_REFUSED = (
    "which Spark holds only with its element or field types, and none is declared "
    "(fields, element, or key and value need contract 0.7.7 or later)"
)
_CLASS_RE = re.compile(r"[A-Za-z]+")
# What may follow a type's name: nothing, or one parenthesised parameter list. Anything after it
# (``int(11) unsigned``, ``timestamp(6) without time zone``) changes the type, and Spark has
# no form for it that this table could guess.
_PARAM_LIST_RE = re.compile(r"\(.*\)", re.DOTALL)


class _Refused(Exception):
    """A column a Spark schema cannot hold: ``why`` reads after ``is declared 'x', ``."""

    def __init__(self, why: str, fix: str) -> None:
        super().__init__(why)
        self.why = why
        self.fix = fix


class _Node(NamedTuple):
    """A rendered type: its lines (continuation lines indented from column 0) and the names
    it needs from ``pyspark.sql.types``."""

    lines: Tuple[str, ...]
    names: FrozenSet[str]


def _text(value: Any) -> str:
    """``value`` as text a UTF-8 file can hold: a lone surrogate (no YAML document has one, a
    JSON one can) becomes ``?`` instead of failing the write."""
    return ("" if value is None else str(value)).encode("utf-8", "replace").decode("utf-8")


def _prose(value: Any) -> str:
    """``value`` as one line of plain text: control characters and line separators (a CR, a
    NUL, U+2028) become spaces and runs of whitespace one space. For a comment or a docstring."""
    return " ".join(py_comment_text(_text(value)).split())


def _lit(value: Any) -> str:
    """A string literal for ``value``: ``repr``, with double quotes where that is safe."""
    text = py_str_literal(value)
    if text.startswith("'") and '"' not in text:
        return '"' + text[1:-1] + '"'
    return text


def _call(name: str, args: Sequence[Sequence[str]]) -> Tuple[str, ...]:
    """``name(arg, ...)`` on one line when every argument is one line and the call fits,
    else one argument to a line with a trailing comma. Depends on its arguments alone, so a
    node renders the same wherever it sits."""
    if all(len(arg) == 1 for arg in args):
        line = f"{name}({', '.join(arg[0] for arg in args)})"
        if len(line) <= _WIDTH:
            return (line,)
    lines = [f"{name}("]
    for arg in args:
        body = list(arg)
        body[-1] += ","
        lines.extend("    " + line for line in body)
    lines.append(")")
    return tuple(lines)


def _bool(value: bool) -> str:
    return "True" if value else "False"


def _scalar(raw: Any) -> column_types.TypeOutcome:
    """What a column type name becomes: its Spark type expression, exact, lossy or refused."""
    base, rest = column_types.split_type(raw)
    if base in column_types.STRUCTURED:
        return column_types.refused(_NESTED_REFUSED, column_types.NESTED_FIX_DECLARE)
    if rest and not _PARAM_LIST_RE.fullmatch(rest):
        return column_types.refused(
            f"whose text after its name, {rest[:40]}, is not a parameter list (Spark has no "
            "unsigned integers, and a time zone is part of the type name)",
            "Declare the type by its name with an optional (p,s) list, or a wider signed "
            "type such as bigint or decimal(20,0) for an unsigned one.",
        )
    # An enum's parameters are its levels, which may hold any character; Spark stores the
    # column as a string and never reads them.
    if base != "enum" and not rest.isascii():
        return column_types.refused(
            f"whose parameters {rest[:40]} are not ASCII", "Declare the type with ASCII digits."
        )
    if base in _DECIMAL_FAMILY:
        return _decimal(rest)
    if base == "bit" and rest not in ("", "(1)"):
        return column_types.refused(
            "which is a bit string, and Spark has none", "Declare binary or an integer type."
        )
    if base in _REFUSED:
        return column_types.refused(*_REFUSED[base])
    if base in _AS_STRING:
        return column_types.lossy(
            "StringType()",
            _AS_STRING[base],
            "Declare string to store the text on purpose; this warning then goes away.",
        )
    hit = _SPARK_TYPES.get(base)
    if hit is None:
        return column_types.refused("which the PySpark emitter does not map", _TYPE_FIX)
    if base == "float" and rest:
        # ``float(53)`` is double precision, as in PostgreSQL and SQL Server.
        digits = rest.strip("()")
        if digits.isascii() and digits.isdigit() and len(digits) <= 9 and int(digits) > 24:
            return column_types.exact("DoubleType()")
    return column_types.exact(hit)


def _decimal(rest: str) -> column_types.TypeOutcome:
    """``decimal(p,s)`` passes through as written; a bare one widens to the Glue default."""
    if not rest:
        return column_types.exact(_DECIMAL_DEFAULT)
    match = _DECIMAL_ARGS_RE.fullmatch(rest)
    if match is not None:
        precision, scale = int(match.group(1)), int(match.group(2) or 0)
        if 1 <= precision <= 38 and scale <= precision:
            return column_types.exact(f"DecimalType({precision}, {scale})")
    return column_types.refused(
        f"whose precision and scale {rest[:40]} are not a Spark decimal's",
        "Declare decimal(p,s) with p from 1 to 38 and s no larger than p, or string.",
    )


def _class_of(expression: str) -> str:
    match = _CLASS_RE.match(expression)
    return match.group(0) if match else expression


def _comment(description: Any) -> Optional[str]:
    """The column's description as one comment line, or ``None``: text only, cut at
    :data:`_COMMENT_WIDTH` characters. It is a ``#:`` line (the convention for documenting a
    name), which no tool reads as a ``# fmt: on`` or ``# noqa`` of its own."""
    if not isinstance(description, str):
        return None
    text = _prose(description)
    if not text:
        return None
    if len(text) > _COMMENT_WIDTH:
        text = text[: _COMMENT_WIDTH - 3].rstrip() + "..."
    return f"#: {text}"


def _child(spec: Any, where: str, depth: int, notes: List[str]) -> _Node:
    if not isinstance(spec, Mapping):
        raise _Refused(f"whose {where} is not a typed definition", column_types.NESTED_FIX)
    return _type_node(spec, where, depth, notes)


def _type_node(spec: Mapping[str, Any], path: str, depth: int, notes: List[str]) -> _Node:
    """The Spark type of a column or nested definition.

    ``notes`` collects one line for each leaf written as a fallback. Raises
    :class:`_Refused` for a declaration Spark cannot hold.
    """
    if depth > MAX_DEPTH:
        raise _Refused(
            f"which nests deeper than {MAX_DEPTH} levels", "Flatten the type or declare string."
        )
    declared = spec.get("type")
    base, _ = column_types.split_type(declared)
    nested = _NESTED_KEYS & spec.keys()
    if base not in column_types.STRUCTURED:
        if nested:
            raise _Refused(
                f"which declares {', '.join(sorted(nested))} but is not a struct, array or map",
                "Declare struct, array or map, or drop the nested types.",
            )
        outcome = _scalar(declared)
        if outcome.status == column_types.REFUSED or outcome.target is None:
            raise _Refused(outcome.why, outcome.fix)
        if outcome.status == column_types.LOSSY:
            notes.append(f"{path} is declared {str(declared)!r}, {outcome.why}")
        return _Node((outcome.target,), frozenset({_class_of(outcome.target)}))
    if not nested:
        raise _Refused(_NESTED_REFUSED, column_types.NESTED_FIX_DECLARE)
    if base in _STRUCT_NAMES:
        allowed = {"fields"}
    elif base == "array":
        allowed = {"element"}
    else:
        allowed = {"key", "value"}
    if nested - allowed:
        raise _Refused(
            f"which declares {', '.join(sorted(nested - allowed))}, and a {base} cannot",
            "Declare fields for a struct, element for an array, key and value for a map.",
        )
    if base in _STRUCT_NAMES:
        return _struct_node(spec.get("fields"), path, depth, notes)
    if base == "array":
        element = spec.get("element")
        node = _child(element, f"{path}.element", depth + 1, notes)
        contains_null = _bool(
            not (isinstance(element, Mapping) and element.get("required") is True)
        )
        return _Node(
            _call("ArrayType", [node.lines, [f"containsNull={contains_null}"]]),
            node.names | {"ArrayType"},
        )
    if "key" not in spec or "value" not in spec:
        raise _Refused("which declares only one of key and value", column_types.NESTED_FIX_DECLARE)
    key = _child(spec.get("key"), f"{path}.key", depth + 1, notes)
    value_spec = spec.get("value")
    value = _child(value_spec, f"{path}.value", depth + 1, notes)
    value_null = _bool(not (isinstance(value_spec, Mapping) and value_spec.get("required") is True))
    return _Node(
        _call("MapType", [key.lines, value.lines, [f"valueContainsNull={value_null}"]]),
        key.names | value.names | {"MapType"},
    )


def _struct_node(fields: Any, path: str, depth: int, notes: List[str]) -> _Node:
    if not isinstance(fields, list) or not fields:
        raise _Refused("which declares no fields", column_types.NESTED_FIX_DECLARE)
    blocks: List[Tuple[str, ...]] = []
    names: set = {"StructType"}
    seen: set = set()
    for field in fields:
        if not isinstance(field, Mapping) or not isinstance(field.get("name"), str):
            raise _Refused("whose fields are not named columns", column_types.NESTED_FIX_DECLARE)
        name = field["name"]
        if not name:
            raise _Refused("which declares a field with an empty name", "Name every field.")
        if name.lower() in seen:
            raise _Refused(
                f"which declares the field name {name!r} twice (names are compared without "
                "regard to case)",
                "Give every field a name that differs by more than its case.",
            )
        seen.add(name.lower())
        lines, used = _field_lines(field, f"{path}.{name}", depth + 1, notes)
        blocks.append(lines)
        names |= used
    body: List[str] = ["StructType(", "    ["]
    for block in blocks:
        lines = list(block)
        lines[-1] += ","
        body.extend("        " + line for line in lines)
    body.extend(["    ]", ")"])
    return _Node(tuple(body), frozenset(names))


def _field_lines(
    column: Mapping[str, Any], path: str, depth: int, notes: List[str]
) -> Tuple[Tuple[str, ...], FrozenSet[str]]:
    """One ``StructField(...)`` for a column, with its description as a comment above it."""
    node = _type_node(column, path, depth, notes)
    nullable = _bool(column.get("required") is not True)
    lines = _call("StructField", [[_lit(column["name"])], node.lines, [f"nullable={nullable}"]])
    comment = _comment(column.get("description"))
    return ((comment,) + lines if comment else lines), node.names | {"StructField"}


def _column_outcome(column: Mapping[str, Any]) -> Optional[column_types.TypeOutcome]:
    """The outcome of a column that declares, or needs, nested types; ``None`` for a plain
    scalar, which :func:`_scalar` judges by its type name."""
    base, _ = column_types.split_type(column.get("type"))
    if base not in column_types.STRUCTURED and not (_NESTED_KEYS & column.keys()):
        return None
    notes: List[str] = []
    try:
        node = _type_node(column, str(column.get("name")), 0, notes)
    except _Refused as exc:
        return column_types.refused(exc.why, exc.fix)
    if notes:
        return column_types.lossy(
            f"{_class_of(node.lines[0])} with StringType() leaves",
            "; ".join(notes),
            "Declare string for those leaves to store the text on purpose; this warning then "
            "goes away.",
        )
    return column_types.exact("\n".join(node.lines))


def column_outcome(column: Mapping[str, Any]) -> column_types.TypeOutcome:
    """What one column becomes in a Spark schema: exact, lossy or refused."""
    return column_types.outcome_of(column, _scalar, _column_outcome)


@dataclass(frozen=True)
class PortModule:
    """One generated module."""

    port: str
    filename: str
    source: str
    columns: int
    warnings: Tuple[str, ...] = ()


@dataclass(frozen=True)
class Rendered:
    """The modules of a contract, the output ports that declare no schema, and the data
    product (its id, else its name)."""

    modules: Tuple[PortModule, ...]
    skipped: Tuple[str, ...]
    product: str = ""


def _shape(why: str) -> UnsupportedBindingError:
    """A contract that is not shaped like one: refused, not skipped, so ``--check`` in CI
    cannot pass on a contract it could not read."""
    return UnsupportedBindingError(
        "contract-shape",
        f"{why}.",
        (
            "Declare exposes as a list of output ports, each with a contract.schema list of columns.",
        ),
    )


def _ports(contract: Any) -> Tuple[List[Tuple[str, List[Any]]], List[str]]:
    """``(ports with columns, ports without)`` of a contract, each port as ``(id, columns)``."""
    if not isinstance(contract, Mapping):
        raise _shape("the contract is not a mapping")
    exposes = contract.get("exposes")
    if exposes is None:
        return [], []
    if not isinstance(exposes, list):
        raise _shape("exposes is not a list of output ports")
    ports: List[Tuple[str, List[Any]]] = []
    skipped: List[str] = []
    for index, exposure in enumerate(exposes):
        if not isinstance(exposure, Mapping):
            raise _shape(f"exposes[{index}] is not an output port definition")
        port = _text(exposure.get("exposeId") or exposure.get("id") or f"port_{index}")
        section = exposure.get("contract")
        if section is not None and not isinstance(section, Mapping):
            raise _shape(f"expose '{port}': contract is not a mapping")
        schema = section.get("schema") if section else None
        if schema is not None and not isinstance(schema, list):
            raise _shape(f"expose '{port}': contract.schema is not a list of columns")
        if schema:
            ports.append((port, schema))
        else:
            skipped.append(port)
    return ports, skipped


def _module_name(identifier: str) -> str:
    """``identifier`` as the stem of a file name: kept whole up to :data:`_MAX_NAME`
    characters, else cut and ended with a hash of the whole so two long ones stay two."""
    if len(identifier) <= _MAX_NAME:
        return identifier
    digest = hashlib.sha256(identifier.encode("utf-8")).hexdigest()[:8]
    return f"{identifier[: _MAX_NAME - 9]}_{digest}"


def _stems(identifiers: Sequence[str]) -> List[str]:
    """One distinct file-name stem for each identifier (the identifiers are distinct already).

    A cut stem can land on another port's whole name, or two hashes can agree, so a stem
    already taken is rebuilt from the identifier and a counter until it is free."""
    used: set = set()
    stems: List[str] = []
    for identifier in identifiers:
        stem, attempt = _module_name(identifier), 1
        while stem in used:
            attempt += 1
            digest = hashlib.sha256(f"{identifier}\0{attempt}".encode("utf-8")).hexdigest()[:8]
            stem = f"{identifier[: _MAX_NAME - 9]}_{digest}"
        used.add(stem)
        stems.append(stem)
    return stems


def render_contract(contract: Mapping[str, Any]) -> Rendered:
    """A module for each output port of ``contract`` that declares ``contract.schema`` columns.

    Raises :class:`~fluid_build.iac.base.UnsupportedBindingError` (kind ``column-type``)
    naming every column no Spark schema can hold, so the author fixes them in one pass; kind
    ``contract-shape`` for a contract, ``exposes`` or ``contract.schema`` that is not the shape
    it needs.
    """
    ports, skipped = _ports(contract)
    product = _text(contract.get("id") or contract.get("name") or "(unnamed)")
    stems = _stems(unique_identifiers(port.lower() for port, _ in ports))

    modules: List[PortModule] = []
    errors: List[UnsupportedBindingError] = []
    for (port, schema), stem in zip(ports, stems, strict=True):
        refusal, warnings = column_types.column_type_findings(
            port, schema, _scalar, "a PySpark schema", column_outcome=_column_outcome
        )
        problem = _name_problem(port, schema)
        if refusal is not None or problem is not None:
            errors.extend(e for e in (refusal, problem) if e is not None)
            continue
        modules.append(
            _render_port(product, port, f"{stem}{SUFFIX}.py", schema, [_text(w) for w in warnings])
        )
    if errors:
        raise _merge(errors)
    return Rendered(tuple(modules), tuple(skipped), product)


def _name_problem(port: str, schema: Sequence[Any]) -> Optional[UnsupportedBindingError]:
    """A column with no name, or two that differ only in case: Spark resolves column names
    without regard to case, so a schema holding both cannot be queried by name."""
    seen: dict = {}
    for position, column in enumerate(schema):
        name = column.get("name") if isinstance(column, Mapping) else None
        if not isinstance(name, str) or not name:
            return UnsupportedBindingError(
                "column-type",
                f"expose '{port}': column {position + 1} has no name.",
                ("Give every column a non-empty name.",),
            )
        if name.lower() in seen:
            return UnsupportedBindingError(
                "column-type",
                f"expose '{port}': columns {seen[name.lower()]!r} and {name!r} differ only in "
                "case, and Spark resolves column names without regard to case.",
                ("Give every column a name that differs by more than its case.",),
            )
        seen[name.lower()] = name
    return None


def _merge(errors: Sequence[UnsupportedBindingError]) -> UnsupportedBindingError:
    remediation: List[str] = []
    for error in errors:
        remediation.extend(r for r in error.remediation if r not in remediation)
    return UnsupportedBindingError(
        "column-type", _text(" ".join(str(e) for e in errors)), tuple(remediation)
    )


def _render_port(
    product: str,
    port: str,
    filename: str,
    schema: Sequence[Any],
    warnings: Sequence[str],
) -> PortModule:
    notes: List[str] = []
    blocks: List[Tuple[str, ...]] = []
    names: set = {"StructType"}
    for column in schema:
        try:
            lines, used = _field_lines(column, str(column["name"]), 0, notes)
        except _Refused as exc:  # pragma: no cover - the findings refuse these first
            raise UnsupportedBindingError(
                "column-type",
                _text(f"expose '{port}': column {column['name']!r} {exc.why}."),
                (exc.fix,),
            ) from exc
        blocks.append(lines)
        names |= used
    body: List[str] = ["SCHEMA = StructType(", "    ["]
    for block in blocks:
        lines = list(block)
        lines[-1] += ","
        body.extend("        " + line for line in lines)
    body.extend(["    ]", ")"])
    needs = (
        ["", "Needs Spark 3.3 or later: it uses TimestampNTZType."]
        if "TimestampNTZType" in names
        else []
    )
    docstring = [
        f'"""Schema of output port \'{escape_for_docstring(_prose(port))}\' of data product '
        f"'{escape_for_docstring(_prose(product))}'.",
        *needs,
        '"""',
    ]
    lines = [
        HEADER,
        CODING,
        "# fmt: off",
        "# isort: skip_file",
        "",
        f"{PRODUCT_PREFIX}{_prose(product)}",
        f"# output port: {_prose(port)}",
        "",
        *docstring,
        "",
        "from pyspark.sql.types import (",
        *(f"    {name}," for name in sorted(names)),
        ")",
        "",
        *body,
        "",
    ]
    source = "\n".join(lines)
    _verify(source, filename, frozenset(names))
    return PortModule(port, filename, source, len(schema), tuple(warnings))


#: The keyword arguments the generated calls pass.
_KEYWORDS = frozenset({"nullable", "containsNull", "valueContainsNull"})


def _verify(source: str, filename: str, names: FrozenSet[str]) -> None:
    """Refuse to return a module that holds anything but a schema.

    A module is imported by a Spark job, so what it holds runs there. It must be exactly a
    docstring, one ``from pyspark.sql.types import`` of the names in ``names`` and ``SCHEMA = ``
    one expression of calls to those names, lists and string, number and boolean constants,
    and its first two lines must be the fixed ones. The check reads the file as the interpreter
    does (bytes, so an encoding declared on line 1 or 2 would apply), not as text.
    """
    first = source.split("\n", 2)[:2]
    if first != [HEADER, CODING]:
        raise ValueError("the generated module does not start with its fixed lines")
    body = ast.parse(source.encode("utf-8"), filename).body
    if (
        len(body) != 3
        or not (
            isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and isinstance(body[0].value.value, str)
        )
        or not (
            isinstance(body[1], ast.ImportFrom)
            and body[1].module == "pyspark.sql.types"
            and body[1].level == 0
            and {a.name for a in body[1].names} == set(names)
            and all(a.asname is None for a in body[1].names)
        )
        or not (
            isinstance(body[2], ast.Assign)
            and len(body[2].targets) == 1
            and isinstance(body[2].targets[0], ast.Name)
            and body[2].targets[0].id == "SCHEMA"
        )
    ):
        raise ValueError("the generated module holds more than its schema")
    for node in ast.walk(body[2].value):
        if isinstance(node, ast.Call):
            allowed = isinstance(node.func, ast.Name) and node.func.id in names
            allowed = allowed and all(k.arg in _KEYWORDS for k in node.keywords)
        elif isinstance(node, ast.Name):
            allowed = node.id in names
        elif isinstance(node, ast.Constant):
            allowed = isinstance(node.value, (str, bool, int))
        else:
            allowed = isinstance(node, (ast.List, ast.keyword, ast.Load))
        if not allowed:
            raise ValueError("the generated module holds more than its schema")


#: Every name a generated module may import from ``pyspark.sql.types``.
TYPE_NAMES: FrozenSet[str] = frozenset(
    {"StructType", "StructField", "ArrayType", "MapType", "StringType", "DecimalType"}
    | {_class_of(expression) for expression in _SPARK_TYPES.values()}
)


def check_module(source: str, filename: str) -> None:
    """Raise ``ValueError`` unless ``source`` is shaped like a module this emitter writes.

    The check :func:`render_contract` applies before it returns a module, for a module read
    back without its contract (``fluid validate-artifacts`` on stage 3's output): the fixed
    first lines, a docstring, one import of names from :data:`TYPE_NAMES`, and ``SCHEMA =``
    one expression of calls to those names. It says nothing about which columns the module
    should hold; regenerate from the contract for that.
    """
    try:
        body = ast.parse(source.encode("utf-8"), filename).body
    except (SyntaxError, ValueError) as exc:
        raise ValueError(f"the module does not parse: {exc}") from None
    imported: FrozenSet[str] = frozenset()
    if len(body) > 1 and isinstance(body[1], ast.ImportFrom):
        imported = frozenset(alias.name for alias in body[1].names)
    if not imported or not imported <= TYPE_NAMES:
        raise ValueError("the generated module holds more than its schema")
    _verify(source, filename, imported)


def is_generated_module(path: Path) -> bool:
    """Whether ``path`` is a regular file (not a link) that starts with :data:`HEADER`."""
    head = _head(path, len(_HEADER_BYTES) + 2)
    return head is not None and _first_lines(head)[0].rstrip(b"\r") == _HEADER_BYTES


# ── Writing ──────────────────────────────────────────────────────────────────

_HEADER_BYTES = HEADER.encode("utf-8")


_PRODUCT_PREFIX_BYTES = PRODUCT_PREFIX.encode("utf-8")


@dataclass(frozen=True)
class Planned:
    """A module, where it goes, and what writing it would do."""

    module: PortModule
    path: Path
    #: new | unchanged | stale | foreign | other_product
    status: str
    #: For ``other_product``: the product the file says it was generated for (one line of plain
    #: text), or ``None`` when its header names none.
    owner: Optional[str] = None


def _head(path: Path, limit: int) -> Optional[bytes]:
    """The first ``limit`` bytes of the regular file ``path``; ``None`` for anything else.

    Never the whole of a large file, and opened without waiting and without following a link,
    then checked on the descriptor: a name swapped for a pipe or a link since it was looked at
    neither blocks the read nor is read through. ``None`` as well when it cannot be read."""
    flags = os.O_RDONLY | getattr(os, "O_NONBLOCK", 0) | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(path, flags)
    except OSError:
        return None
    try:
        if not stat.S_ISREG(os.fstat(descriptor).st_mode):
            return None
        chunks: List[bytes] = []
        remaining = limit
        while remaining > 0:
            chunk = os.read(descriptor, min(remaining, 1 << 20))
            if not chunk:
                break
            chunks.append(chunk)
            remaining -= len(chunk)
        return b"".join(chunks)
    except OSError:
        return None
    finally:
        os.close(descriptor)


def _product_line(source: str) -> Optional[bytes]:
    """The ``# data product: ...`` line among the first lines of a module's own source."""
    for line in source.split("\n")[:10]:
        if line.startswith(PRODUCT_PREFIX):
            return line.encode("utf-8")
    return None


def _first_lines(head: bytes) -> List[bytes]:
    """The first ten lines of a file's head, whatever its line endings."""
    return head.replace(b"\r\n", b"\n").split(b"\n")[:10]


def _owner_of(head: bytes) -> Optional[str]:
    """The product a header file says it was generated for, as one line of plain text."""
    for line in _first_lines(head):
        if line.startswith(_PRODUCT_PREFIX_BYTES):
            return _prose(line[len(_PRODUCT_PREFIX_BYTES) :].decode("utf-8", "replace"))[:80]
    return None


def plan(modules: Sequence[PortModule], out_dir: Path) -> List[Planned]:
    """What each module would do in ``out_dir``: ``new`` (no file), ``unchanged``, ``stale``
    (a file this command wrote for THIS product, now different), ``other_product`` (a file this
    command wrote for another product, or one whose header names none: two products that share an
    output directory and a port id must not replace each other's module) or ``foreign`` (a file it
    did not write, or one it cannot read, or a link). Only ``new`` and ``stale`` are ever written.
    """
    planned: List[Planned] = []
    for module in modules:
        path = out_dir / module.filename
        owner: Optional[str] = None
        if path.is_symlink() or (path.exists() and not path.is_file()):
            status = "foreign"
        elif not path.exists():
            status = "new"
        else:
            wanted = module.source.encode("utf-8")
            # Twice the module's size is room for a copy whose line endings were converted.
            limit = 2 * len(wanted) + 1
            head = _head(path, limit)
            if head is None:
                status = "foreign"
            elif len(head) < limit and head.replace(b"\r\n", b"\n") == wanted:
                status = "unchanged"
            elif head.startswith(_HEADER_BYTES):
                ours = _product_line(module.source)
                if ours is None or ours in _first_lines(head):
                    status = "stale"
                else:
                    status, owner = "other_product", _owner_of(head)
            else:
                status = "foreign"
        planned.append(Planned(module, path, status, owner))
    return planned


def orphans(out_dir: Path, modules: Sequence[PortModule], product: str) -> List[str]:
    """The ``*_schema.py`` files in ``out_dir`` that this command wrote for ``product`` and the
    contract no longer generates (a port renamed or dropped). Another product's modules in the
    same directory are not its business, and a file that cannot be read is skipped. Never
    deleted: a run notes them and ``--check`` fails on them."""
    wanted = {module.filename for module in modules}
    line = f"{PRODUCT_PREFIX}{_prose(product)}".encode("utf-8")
    found: List[str] = []
    try:
        candidates = sorted(out_dir.glob(f"*{SUFFIX}.py"))
    except OSError:
        return []
    for path in candidates:
        if path.name in wanted or path.is_symlink():
            continue
        head = _head(path, 512 + len(line))
        if head is not None and head.startswith(_HEADER_BYTES) and line in head.split(b"\n")[:10]:
            found.append(path.name)
    return found


def _created_mode() -> int:
    """The mode ``open()`` gives a new file under the process umask: a generated module is a
    source file, read like the rest of the checkout (``atomic_write_bytes`` defaults to
    owner-only)."""
    mask = os.umask(0)
    os.umask(mask)
    return 0o666 & ~mask


def write(planned: Sequence[Planned]) -> None:
    """Write every ``new`` and ``stale`` module (UTF-8, ``\\n``), each by replacing the file
    whole through a sibling that is created exclusively (``atomic_write_bytes``), so a reader
    of the directory never sees half a module and a link planted at the sibling's name is
    refused, not written through."""
    for item in planned:
        if item.status not in ("new", "stale"):
            continue
        item.path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_bytes(item.path, item.module.source.encode("utf-8"), mode=_created_mode())
