"""PySpark ``StructType`` modules: one Python module per output port of a contract.

``fluid generate pyspark-schema`` reads each output port's ``contract.schema`` and writes
``<port>_schema.py``, a module a Spark job imports for the port's schema::

    from orders_schema import SCHEMA
    df = spark.read.schema(SCHEMA).parquet(path)

This module renders text. It never imports ``pyspark``, so forge-cli needs no pyspark: the
generated module is the only place that imports it, when a job on a cluster imports the module.

A column's type is classified as the Glue and BigQuery emitters classify theirs
(:mod:`fluid_build.iac.column_types`):

* ``exact``: a Spark type holds every value the declared type does.
* ``lossy``: Spark has no such type, ``StringType()`` is written and the caller warns
  (``json``, ``variant``, ``time``, ``interval``).
* ``refused``: no form worth writing, so nothing is written (a spatial type, a decimal Spark
  cannot hold, a struct, array or map that declares no nested types).

A struct, array or map declares its nested types as ``fields``, ``element``, or ``key`` and
``value`` (contract 0.7.7), and each level is judged the same way. ``required: true`` is
``nullable=False``, as ``containsNull`` and ``valueContainsNull`` are for an element or value.
Spark's file sources and ``from_json`` read every column as nullable whatever is declared, so
``nullable=False`` is documentation there and a check in ``spark.createDataFrame``.

The Spark transformation engine's ``OUTPUT_SCHEMA`` (``engines/spark``) is a flat skeleton inside
a job template (an unknown type is silently ``StringType()``, a decimal is always (18, 2), every
column is nullable), and :func:`fluid_build.streaming.types.parse_type` is Flink-shaped (it refuses
``smallint`` and a map key that is not a required string), so neither is extended here.

The output is deterministic: contract order, no timestamp, no version. Contract text reaches
the source only as a ``repr`` string literal, as ``#`` comment text or as docstring text, each with
its control characters and line separators replaced, never on the first two lines (an encoding
declaration there would change how the interpreter decodes the file), and the finished module is
checked against an allowlist of exactly what it may hold before it is returned.
"""

