"""The agent skills pack: Agent Skills (agentskills.io ``SKILL.md``) for coding agents.

This directory is three things at once, from one copy of the files:

* package data, which ``fluid scaffold-ide`` copies into a workspace's
  ``.claude/skills/`` or ``.agents/skills/``;
* a Claude Code plugin root (``.claude-plugin/plugin.json``, ``hooks/hooks.json``,
  ``skills/``) that the repository's ``.claude-plugin/marketplace.json`` lists;
* the layout ``npx skills add`` (vercel-labs/skills) installs, found through that
  same marketplace file.

The reference sheets under ``skills/*/references/`` are generated by
``scripts/gen_agent_skill_references.py``; ``tests/agent_skills`` fails when they drift.
Layout borrowed from dbt-labs/dbt-agent-skills and hashicorp/agent-skills (a plugin per
directory, ``skills/<name>/SKILL.md`` below it).

Standard library plus PyYAML only: ``scaffold-ide`` imports this when it runs.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List

PACK_DIR = Path(__file__).resolve().parent
SKILLS_DIR = PACK_DIR / "skills"


def skill_dirs() -> List[Path]:
    """Every skill directory in the pack, in name order."""
    return sorted(p.parent for p in SKILLS_DIR.glob("*/SKILL.md"))


def skill_files(skill_dir: Path) -> List[Path]:
    """Every file a skill ships, relative to its directory, in a stable order."""
    return sorted(
        p.relative_to(skill_dir)
        for p in skill_dir.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    )


def frontmatter(skill_md: Path) -> Dict[str, object]:
    """The YAML block between the two ``---`` lines that open a ``SKILL.md``."""
    import yaml

    text = skill_md.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{skill_md}: SKILL.md must open with a '---' frontmatter line")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValueError(f"{skill_md}: SKILL.md frontmatter is not closed by '---'")
    data = yaml.safe_load(text[4:end]) or {}
    if not isinstance(data, dict):
        raise ValueError(f"{skill_md}: SKILL.md frontmatter must be a mapping")
    return data


def summary(skill_md: Path) -> str:
    """The first sentence of a skill's description: what it does, for an index line."""
    description = str(frontmatter(skill_md).get("description", "")).strip()
    head, sep, _ = description.partition(". ")
    return head + "." if sep else description
