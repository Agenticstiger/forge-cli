"""Generate ``profiles.yml`` template based on target platform."""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import yaml

from .project_yml import _sanitize_project_name
from .sources import _normalize_placeholder

_logger = logging.getLogger(__name__)

#: The one dbt Jinja form a contract value may carry as written:
#: ``{{ env_var('NAME') }}``, with an optional quoted default. Anything else
#: (``~``, ``{% set %}``, a call written any other way) is evaluated by dbt as
#: written, so it is refused rather than parsed. The default holds no ``$`` or
#: brace, so no placeholder in it can turn into a second, nested call, and no
#: backslash: Jinja reads ``'\'`` as an open string, so the call would run on
#: past the point this pattern ends it.
_ENV_VAR_JINJA_RE = re.compile(
    r"\{\{\s*env_var\(\s*'([A-Za-z_][A-Za-z0-9_]*)'\s*(?:,\s*'[^'{}%#$\\]*'\s*)?\)\s*\}\}"
)
#: Left over once the allowed calls are taken out, any of these is Jinja the
#: allowlist did not match: an opening one starts code, a closing one ends a
#: call that ran on past where the pattern ended it.
_JINJA_MARKERS = ("{{", "{%", "{#", "}}", "%}", "#}")

_HEADER = "# Generated by fluid generate — do not edit manually.\n# Regenerate with: fluid generate\n#\n# Fill in the placeholder values or use dbt env_var() for secrets.\n\n"

# Last-resort target schema when the contract declares none. ``PUBLIC`` is
# only correct when the contract really is schema-less — resolving the
# declared schema (below) takes precedence, because a profile that silently
# writes to PUBLIC builds every model in the wrong place on a green
# ``dbt debug``.
_SCHEMA_FALLBACK = (
    "{{ env_var('SNOWFLAKE_DBT_SCHEMA', env_var('SNOWFLAKE_FLUID_SCHEMA', 'PUBLIC')) }}"
)


def generate_profiles(
    contract: Dict[str, Any],
    build: Dict[str, Any],
    *,
    output_dir: Optional[Path] = None,
) -> Optional[str]:
    """Generate ``profiles.yml`` template content."""
    from . import _types as _types

    contract_id = contract.get("id", "fluid_project")
    profile_name = _sanitize_project_name(contract_id)

    profile = _profile_for_platform(
        _types.build_platform(build, contract),
        profile_name,
        output_dir=output_dir,
        schema_expr=resolve_schema_expr(contract, build),
        catalog_expr=resolve_catalog_expr(contract, build),
    )
    if not profile:
        return None

    return _HEADER + yaml.dump(
        profile, default_flow_style=False, sort_keys=False, allow_unicode=True
    )


def resolve_schema_expr(
    contract: Dict[str, Any],
    build: Dict[str, Any],
) -> Optional[str]:
    """Resolve the dbt target schema the *contract* declares.

    ``profiles.yml`` used to hardcode
    ``env_var('SNOWFLAKE_DBT_SCHEMA', env_var('SNOWFLAKE_FLUID_SCHEMA', 'PUBLIC'))``
    and never look at the contract at all, so a contract declaring
    ``builds[].execution.runtime.resources.schema`` built every model into
    ``PUBLIC`` while ``dbt debug`` reported "connection ok" — the failure was
    asymmetric because ``database`` *was* resolved correctly.

    Precedence:

    1. ``builds[].execution.runtime.resources.schema`` (or ``dataset`` on
       BigQuery) — the build's own declared target.
    2. The schema on the first ``exposes[].binding.location`` — where the
       contract says its outputs land.

    ``{{ env.X }}`` / ``${X}`` placeholders are translated to dbt's
    ``env_var('X')`` by the same normaliser ``sources.py`` uses, so the two
    emitters agree on how contract placeholders reach dbt. Returns ``None``
    when the contract declares no schema, leaving the caller's env-var
    fallback in place.
    """
    return _declared_expr(contract, build, ("schema", "dataset"), ("schema", "dataset"))


def resolve_catalog_expr(
    contract: Dict[str, Any],
    build: Dict[str, Any],
) -> Optional[str]:
    """Resolve the Unity Catalog catalog the contract declares, for Databricks.

    ``builds[].execution.runtime.resources.catalog`` first (the key the dbt
    runner reads, ``build_runners/dbt/profiles.py``), then the first Databricks
    expose's ``binding.location.database``, which is where the IaC emitter
    creates the schema. Placeholders translate as in :func:`resolve_schema_expr`.
    """
    return _declared_expr(contract, build, ("catalog",), ("database",), platform="databricks")


def _declared_expr(
    contract: Dict[str, Any],
    build: Dict[str, Any],
    resource_keys: Tuple[str, ...],
    location_keys: Tuple[str, ...],
    *,
    platform: Optional[str] = None,
) -> Optional[str]:
    """The first of ``resource_keys`` the build's runtime resources declare, else the
    first of ``location_keys`` on an expose binding (of ``platform``, when given)."""
    execution = build.get("execution", {}) if isinstance(build, dict) else {}
    runtime = execution.get("runtime", {}) if isinstance(execution, dict) else {}
    resources = runtime.get("resources", {}) if isinstance(runtime, dict) else {}
    candidates = [(resources, resource_keys)] if isinstance(resources, dict) else []
    for expose in contract.get("exposes", []) or []:
        binding = expose.get("binding") if isinstance(expose, dict) else None
        if isinstance(binding, dict) and platform in (None, binding.get("platform")):
            location = binding.get("location")
            if isinstance(location, dict):
                candidates.append((location, location_keys))
    for values, keys in candidates:
        for key in keys:
            normalized = _contract_expr(values.get(key))
            if normalized:
                return normalized
    return None


def _contract_expr(value: Any) -> Optional[str]:
    """``value`` as profiles.yml Jinja, or ``None`` when it may not go there.

    An allowlist: besides literal text the value may carry FLUID placeholders
    (``{{ env.NAME }}``, ``${NAME}``, translated to ``env_var('NAME')``) and
    dbt's own ``{{ env_var('NAME') }}``, nothing else dbt would evaluate. And no
    NAME may be credential-shaped: ``{{ env.DATABRICKS_TOKEN }}`` as a catalog
    puts the secret where dbt prints names back (``catalog not found``, run
    logs), the names ``resolve_env_templates_in_contract`` refuses to resolve.
    A refused value is not used; the caller falls back to its environment default.

    Checked as emitted, after the translation: ``{{ env.X }}`` inside an
    ``env_var`` default only becomes a second, nested call there.
    """
    from fluid_build.observability.secret_redactor import is_sensitive_key_name

    text = str(value).strip() if value is not None else ""
    if not text:
        return None
    emitted = _normalize_placeholder(text) or ""
    if any(marker in _ENV_VAR_JINJA_RE.sub("", emitted) for marker in _JINJA_MARKERS):
        _logger.warning("profiles.yml: a contract value carries Jinja; not used")
        return None
    names = _ENV_VAR_JINJA_RE.findall(emitted)
    secret = next((name for name in names if is_sensitive_key_name(name)), None)
    if secret:
        _logger.warning(
            "profiles.yml: a contract value reads %s, a credential-shaped variable; not used",
            secret,
        )
        return None
    return emitted


def _profile_for_platform(
    platform: str,
    profile_name: str,
    *,
    output_dir: Optional[Path] = None,
    schema_expr: Optional[str] = None,
    catalog_expr: Optional[str] = None,
) -> Dict[str, Any]:
    """Build a profiles.yml dict for the given platform."""
    lower = platform.lower()

    if lower in ("gcp", "bigquery"):
        return {
            profile_name: {
                "target": "dev",
                "outputs": {
                    "dev": {
                        "type": "bigquery",
                        "method": "oauth",
                        "project": "{{ env_var('GCP_PROJECT') }}",
                        "dataset": schema_expr or "analytics_dev",
                        "threads": 4,
                        "location": "US",
                    },
                    "prod": {
                        "type": "bigquery",
                        "method": "oauth",
                        "project": "{{ env_var('GCP_PROJECT') }}",
                        "dataset": schema_expr or "analytics",
                        "threads": 8,
                        "location": "US",
                    },
                },
            }
        }

    if lower in ("snowflake",):
        # All Snowflake connection parameters are sourced from env vars so
        # the same profiles.yml works across environments. The target schema
        # comes from the contract when it declares one (see
        # ``resolve_schema_expr``); the env-var chain is only the fallback
        # for a contract that declares no schema at all.
        return {
            profile_name: {
                "target": "dev",
                "outputs": {
                    "dev": {
                        "type": "snowflake",
                        "account": "{{ env_var('SNOWFLAKE_ACCOUNT') }}",
                        "user": "{{ env_var('SNOWFLAKE_USER') }}",
                        "password": "{{ env_var('SNOWFLAKE_PASSWORD') }}",
                        "role": "{{ env_var('SNOWFLAKE_ROLE') }}",
                        "database": "{{ env_var('SNOWFLAKE_DATABASE') }}",
                        "warehouse": "{{ env_var('SNOWFLAKE_WAREHOUSE') }}",
                        "schema": schema_expr or _SCHEMA_FALLBACK,
                        "threads": 4,
                    },
                },
            }
        }

    if lower == "databricks":
        return _databricks_profile(profile_name, schema_expr, catalog_expr)

    if lower in ("aws", "redshift"):
        return {
            profile_name: {
                "target": "dev",
                "outputs": {
                    "dev": {
                        "type": "redshift",
                        "host": "{{ env_var('REDSHIFT_HOST') }}",
                        "user": "{{ env_var('REDSHIFT_USER') }}",
                        "password": "{{ env_var('REDSHIFT_PASSWORD') }}",
                        "port": 5439,
                        "dbname": "analytics",
                        "schema": schema_expr or "dev",
                        "threads": 4,
                    },
                },
            }
        }

    # Default: local / DuckDB. Use a project-local absolute path when
    # the generator knows the output directory so `dbt run --project-dir`
    # works from any current working directory.
    duckdb_path = (
        str((output_dir / "dev.duckdb").resolve()) if output_dir is not None else "dev.duckdb"
    )
    return {
        profile_name: {
            "target": "dev",
            "outputs": {
                "dev": {
                    "type": "duckdb",
                    "path": duckdb_path,
                    "threads": 4,
                },
            },
        }
    }


def _databricks_profile(
    profile_name: str, schema_expr: Optional[str], catalog_expr: Optional[str]
) -> Dict[str, Any]:
    """The Databricks target: the same keys and environment variables as the dbt
    runner's own profile (``build_runners/dbt/profiles.py``), so a profiles.yml
    written here and the one the runner generates connect the same way. The
    catalog is the contract's ``location.database``, the catalog the IaC emitter
    creates the schema in."""
    dev = {
        "type": "databricks",
        "host": "{{ env_var('DATABRICKS_HOST') }}",
        "http_path": "{{ env_var('DATABRICKS_HTTP_PATH') }}",
        "token": "{{ env_var('DATABRICKS_TOKEN') }}",
        "catalog": catalog_expr or "{{ env_var('DATABRICKS_CATALOG') }}",
        "schema": schema_expr or "{{ env_var('DATABRICKS_SCHEMA', 'default') }}",
        "threads": 4,
    }
    return {profile_name: {"target": "dev", "outputs": {"dev": dev}}}
