def _model_window(semantics: Mapping[str, Any], expose_id: Any) -> Optional[Tuple[str, str, str]]:
    """The expose's validity window, or ``None``; a malformed one is dropped with a warning.

    ``validity_window`` holds the rules ``fluid validate`` reports, a bound whose
    MetricFlow name another entity or dimension also takes among them, so the bridge
    never writes a window with one bound (dbt rejects it).
    """
    window = validity_window(semantics)
    if window is None and declares_validity_params(semantics):
        logger.warning(
            "semantic_models: expose %r declares validityParams that do not form a validity "
            "window (fluid validate names the problem), so its validity params are dropped",
            expose_id,
        )
    return window


def _model_measures(
    semantics: Mapping[str, Any],
    expose: Mapping[str, Any],
    dimensions: List[Dict[str, Any]],
    used_names: Set[str],
    window: Optional[Tuple[str, str, str]],
    model_name: str,
) -> Tuple[Optional[str], List[Dict[str, Any]]]:
    """``(agg_time_dimension, measures)`` for one model; ``(None, [])`` when dbt would reject them.

    Measures need an aggregation time dimension, and dbt accepts none beside a
    validity window.
    """
    if window is not None:
        if semantics.get("measures"):
            logger.warning(
                "semantic_models: expose %r has measures beside a validity window, which "
                "dbt MetricFlow does not accept: measures + metrics dropped",
                get_expose_id(expose),
            )
        return None, []
    agg_time_dim = _resolve_agg_time_dimension(semantics, dimensions, expose, used_names)
    if agg_time_dim is None:
        if semantics.get("measures"):
            logger.warning(
                "semantic_models: expose %r has measures but no resolvable "
                "time dimension: measures + metrics dropped",
                get_expose_id(expose),
            )
        return None, []
    time_dims = {d["name"] for d in dimensions if d.get("type") == "time"}
    return agg_time_dim, _build_measures(semantics, used_names, time_dims, model_name)


def generate_semantic_models(
    contract: Dict[str, Any],
    emitted_models: Optional[Set[str]] = None,
) -> GenerationResult:
    """Emit ``models/semantic_models.yml`` from ``exposes[*].semantics``.

    Returns ``{}`` (graceful no-op) when no expose carries a semantics
    block — hand-authored contracts often lack one, and the generated
    project must stay byte-identical for them.

    ``emitted_models`` is the set of model names this generation actually
    wrote (basenames, no ``.sql``). A semantic model's ``model:`` key is
    ``ref('<exposeId>')``, but the intent / multi-stage / embedded-logic
    model emitters name their files from *stage* names, so on those paths
    the ref points at a node that does not exist and ``dbt parse`` fails
    the whole project::

        Semantic_Model 'semantic_model.x.orders' depends on a node named
        'orders' which was not found

    When the caller supplies the emitted set, a semantic model whose ref
    target is missing is dropped with a loud warning rather than poisoning
    the project. Callers that pass nothing keep the previous behaviour.
    """
    semantic_models: List[Dict[str, Any]] = []
    all_metrics: List[Dict[str, Any]] = []
    deferred_metrics: List[Dict[str, Any]] = []
    metric_names_taken: Set[str] = set()
    emitted_metric_names: Set[str] = set()
    model_names_taken: Set[str] = set()

    for expose in get_exposes(contract):
        if not isinstance(expose, dict):
            continue
        semantics = expose.get("semantics")
        if not isinstance(semantics, Mapping) or not semantics:
            continue
        expose_id = get_expose_id(expose)
        if not expose_id:
            continue
        model_name = _sanitize_name(expose_id)
        if not model_name or model_name in model_names_taken:
            continue

        semantics = _listed_collections(semantics, expose_id)
        window = _model_window(semantics, expose_id)
        entities = _build_entities(semantics, expose, model_name, window)
        if not entities:
            logger.warning(
                "semantic_models: skipping expose %r (no primary entity could be derived)",
                expose_id,
            )
            continue

        used_names: Set[str] = {e["name"] for e in entities}
        dimensions = _build_dimensions(semantics, used_names, window)
        agg_time_dim, measures = _model_measures(
            semantics, expose, dimensions, used_names, window, model_name
        )

        if emitted_models is not None and expose_id not in emitted_models:
            logger.warning(
                "semantic_models: skipping expose %r — its ref('%s') target is not "
                "among the emitted models (%s). Emitting it would make `dbt parse` "
                "fail for the whole project.",
                expose_id,
                expose_id,
                ", ".join(sorted(emitted_models)) or "none",
            )
            continue

        model_def: Dict[str, Any] = {
            "name": model_name,
            "model": f"ref('{expose_id}')",
        }
        description = semantics.get("description") or expose.get("description")
        if description:
            model_def["description"] = str(description)
        meta = _semantic_model_meta(semantics)
        if meta:
            # tags/labels ride in config.meta (dbt-parse-verified on 1.11;
            # round-tripped by the manifest importer via fluid_tags /
            # fluid_labels keys).
            model_def["config"] = {"meta": meta}
        if agg_time_dim is not None and measures:
            model_def["defaults"] = {"agg_time_dimension": agg_time_dim}
        if window is not None:
            # dbt's SCD type II shape: the natural entity stands in as the
            # primary entity a model with dimensions must have.
            model_def["primary_entity"] = _sanitize_name(window[2])
        model_def["entities"] = entities
        if dimensions:
            model_def["dimensions"] = dimensions
        if measures:
            model_def["measures"] = measures

        semantic_models.append(model_def)
        model_names_taken.add(model_name)

        measure_names = {m["name"] for m in measures}
        # A ``create_metric`` measure auto-creates a metric bearing its
        # name — that name is claimed (an explicit same-named metric
        # would collide at parse) and counts as resolvable input for
        # ratio/derived metrics.
        create_metric_names = {m["name"] for m in measures if m.get("create_metric")}
        metric_names_taken.update(create_metric_names)
        emitted_metric_names.update(create_metric_names)

        simple_metrics = _build_metrics(
            semantics, measure_names, metric_names_taken, model_name, deferred_metrics
        )
        emitted_metric_names.update(m["name"] for m in simple_metrics)
        all_metrics.extend(simple_metrics)

    if not semantic_models:
        return {}

    all_metrics.extend(_resolve_deferred_metrics(deferred_metrics, emitted_metric_names))

    data: Dict[str, Any] = {"semantic_models": semantic_models}
    if all_metrics:
        data["metrics"] = all_metrics
    # MetricFlow refuses to parse a project with semantic models but no
    # day-grain (or smaller) time spine. Ship one + its YAML config.
    data["models"] = [_TIME_SPINE_MODEL_DEF]
    content = _HEADER + yaml.dump(
        data, default_flow_style=False, sort_keys=False, allow_unicode=True
    )
    return {
        "models/semantic_models.yml": content,
        "models/metricflow_time_spine.sql": _TIME_SPINE_SQL,
    }
