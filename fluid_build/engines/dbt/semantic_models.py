def _build_entities(
    semantics: Mapping[str, Any],
    expose: Mapping[str, Any],
    model_name: str,
    window: Optional[Tuple[str, str, str]] = None,
) -> List[Dict[str, Any]]:
    """Map contract entities, guaranteeing exactly one primary entity.

    With a validity ``window`` the model takes dbt's SCD type II shape instead:
    the natural entity plus foreign ones, and no primary entity (the caller
    sets ``primary_entity:`` to the natural one), because dbt rejects a primary
    or unique entity beside a window.
    """
    entities: List[Dict[str, Any]] = []
    seen: Set[str] = set()
    have_primary = False

    for raw in semantics.get("entities") or []:
        if not isinstance(raw, Mapping) or not raw.get("name"):
            continue
        name = _sanitize_name(raw["name"])
        if not name or name in seen:
            continue
        etype = str(raw.get("type") or "foreign").strip().lower()
        if etype not in ("primary", "foreign", "unique", "natural"):
            etype = "foreign"
        if not _entity_fits_window(etype, window, raw.get("name"), model_name):
            continue
        if etype == "primary":
            if have_primary:
                # MetricFlow allows at most one primary entity.
                etype = "unique"
            else:
                have_primary = True
        entity: Dict[str, Any] = {"name": name, "type": etype}
        if raw.get("expr"):
            entity["expr"] = str(raw["expr"])
        if raw.get("description"):
            entity["description"] = str(raw["description"])
        entities.append(entity)
        seen.add(name)

    if window is not None:
        return entities
    if not have_primary:
        derived = _derive_primary_entity(expose, model_name, seen)
        if derived is None:
            # Last resort: promote the first unique entity to primary.
            for entity in entities:
                if entity["type"] == "unique":
                    entity["type"] = "primary"
                    have_primary = True
                    break
        else:
            entities.insert(0, derived)
            have_primary = True

    if not have_primary:
        return []
    return entities


def _entity_fits_window(
    etype: str, window: Optional[Tuple[str, str, str]], name: Any, model_name: str
) -> bool:
    """False, with a warning, for an entity dbt rejects given the model's validity window.

    dbt accepts no primary or unique entity beside a window, and a natural entity
    only with one (dbt-semantic-interfaces ``SemanticModelValidityWindowRule`` and
    ``NaturalEntityConfigurationRule``).
    """
    if window is not None and etype in ("primary", "unique"):
        logger.warning(
            "semantic_models: dropping %s entity %r on %s (dbt MetricFlow accepts no "
            "primary or unique entity beside a validity window)",
            etype,
            name,
            model_name,
        )
        return False
    if window is None and etype == "natural":
        logger.warning(
            "semantic_models: dropping natural entity %r on %s (dbt MetricFlow accepts a "
            "natural entity only with a validity window: two time dimensions with "
            "typeParams.validityParams)",
            name,
            model_name,
        )
        return False
    return True


def _derive_primary_entity(
    expose: Mapping[str, Any],
    model_name: str,
    taken: Set[str],
) -> Optional[Dict[str, Any]]:
    """Derive a primary entity from the expose's declared key column.

    Mirrors the forge semantics emitter's naming (``order_id`` → entity
    ``order`` with ``expr: order_id``). Falls back to the first schema
    column when no column is declared a key.
    """
    columns = _schema_columns(expose)
    key_col: Optional[str] = None
    for col in columns:
        if _tm.column_is_key(col):
            key_col = str(col["name"])
            break
    if key_col is None and columns:
        key_col = str(columns[0]["name"])
    if key_col is None:
        return None

    base = _sanitize_name(re.sub(r"_id$", "", key_col) or key_col)
    if not base:
        base = _sanitize_name(key_col)
    if not base:
        return None
    if base in taken:
        base = _sanitize_name(f"{model_name}_{base}")
        if not base or base in taken:
            return None
    return {"name": base, "type": "primary", "expr": key_col}


