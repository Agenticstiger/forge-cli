# Undefined names that are PRE-EXISTING and deliberately out of scope for this
# security change: `cprint` (a typo for print) and `success` in the Prefect
# emitters. They are recorded as acceptance criteria on the Prefect 3 port
# (issue #631). Allow-listed here so this oracle still fails on any NEW
# undefined name introduced by identifier work — which is what it is for.
_KNOWN_PREEXISTING_UNDEFINED = {"cprint", "success"}


def _assert_no_undefined_names(code: str) -> None:
    tree = ast.parse(code)
    bound = set(dir(__import__("builtins"))) | _KNOWN_PREEXISTING_UNDEFINED
    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            bound.update((a.asname or a.name).split(".")[0] for a in node.names)
        elif isinstance(node, ast.Name) and isinstance(node.ctx, (ast.Store, ast.Del)):
            bound.add(node.id)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            bound.add(node.name)
            args = getattr(node, "args", None)
            if args is not None:
                bound.update(
                    a.arg
                    for a in [*args.posonlyargs, *args.args, *args.kwonlyargs]
                    + [args.vararg, args.kwarg]
                    if a is not None
                )
        elif isinstance(node, ast.Lambda):
            a = node.args
            bound.update(
                x.arg
                for x in [*a.posonlyargs, *a.args, *a.kwonlyargs] + [a.vararg, a.kwarg]
                if x is not None
            )
    undefined = sorted(
        {
            n.id
            for n in ast.walk(tree)
            if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load) and n.id not in bound
        }
    )
    assert not undefined, f"generated file references undefined names {undefined}\n---\n{code}"


@pytest.mark.parametrize("emitter", _ids())
def test_leading_digit_task_id_wires_to_a_name_that_exists(emitter):
    """The `def` name and the dependency `_result` value must agree.

    ``task_identifier`` prefixes a leading digit where ``sanitize_identifier``
    strips it, so deriving the two halves of a dependency edge with different
    helpers emits a reference to a name the module never binds — and if a
    sibling task happens to match the stripped form, it silently wires the
    WRONG upstream instead of failing.
    """
    c = _contract(name="Orders", description="ordinary")
    c["orchestration"]["tasks"] = [
        {
            "taskId": "2024_load",
            "type": "provider_action",
            "action": "x.s3.ensure_bucket",
            "params": {"bucket": "b", "sql": "SELECT 1", "query": "SELECT 1", "database": "d"},
        },
        {
            "taskId": "report",
            "type": "provider_action",
            "action": "x.s3.ensure_bucket",
            "params": {"bucket": "c", "sql": "SELECT 2", "query": "SELECT 2", "database": "d"},
            "dependsOn": ["2024_load"],
        },
    ]
    _assert_no_undefined_names(_fn(emitter)(c))


@pytest.mark.parametrize("emitter", _ids())
def test_leading_digit_does_not_wire_to_a_sibling(emitter):
    """The silent-miswire variant: a sibling named like the stripped form."""
    c = _contract(name="Orders", description="ordinary")
    common = {"bucket": "b", "sql": "SELECT 1", "query": "SELECT 1", "database": "d"}
    c["orchestration"]["tasks"] = [
        {
            "taskId": "2024_load",
            "type": "provider_action",
            "action": "x.s3.ensure_bucket",
            "params": dict(common),
        },
        {
            "taskId": "_load",
            "type": "provider_action",
            "action": "x.s3.ensure_bucket",
            "params": dict(common),
        },
        {
            "taskId": "report",
            "type": "provider_action",
            "action": "x.s3.ensure_bucket",
            "params": dict(common),
            "dependsOn": ["2024_load"],
        },
    ]
    code = _fn(emitter)(c)
    _assert_no_undefined_names(code)
    # `_load_result` legitimately exists as the `_load` task's own binding, so
    # check the EDGE specifically: every line wiring `report` to an upstream
    # must reference the 2024_load binding, not the sibling's.
    # Emitters differ in idiom: some pass `<op>_result`, some pass the op
    # itself. Either is fine — what matters is that the NAME is the 2024_load
    # binding and never the `_load` sibling's.
    # NB: some Prefect emitters drop the edge entirely today (`task_results` is
    # built and never read) — a pre-existing defect tracked on issue #631, not
    # this change's to fix. So this asserts "if an edge is emitted, it names the
    # right upstream", which is the identifier-agreement property under test.
    edge_lines = [ln for ln in code.splitlines() if "report" in ln and "_load" in ln]
    for ln in edge_lines:
        assert (
            "task_2024_load" in ln
        ), f"dependency edge wired to the wrong upstream: {ln.strip()!r}"


def test_json_literal_matches_json_dumps_key_spelling():
    """Keys must be coerced the way json.dumps spells them, not via str().

    PyYAML is YAML 1.1, so a bare ``on:``/``off:``/``yes:``/``no:``/``~:`` key
    parses to bool/None. ``str(True)`` is ``"True"``; JSON spells it ``"true"``.
    Getting this wrong silently renames keys in the generated output — and one
    call site ships that string straight to AWS Lambda.
    """
    from fluid_build.providers.common.codegen_utils import json_literal

    assert json_literal({True: "a", False: "b"}) == repr('{"false": "b", "true": "a"}')
    assert json_literal({None: "n"}) == repr('{"null": "n"}')
    assert json_literal({1: "x", 2.5: "y"}) == repr('{"1": "x", "2.5": "y"}')


def test_json_literal_survives_mixed_type_keys():
    """The regression shipped in #630: sort_keys=True cannot compare mixed types."""
    from fluid_build.providers.common.codegen_utils import json_literal

    assert json_literal({"a": 1, 2: "b"}) == repr('{"2": "b", "a": 1}')


def test_task_identifier_keeps_leading_digit_ids_distinct():
    from fluid_build.providers.common.codegen_utils import task_identifier

    assert task_identifier("2024_run") != task_identifier("9999_run")
    assert task_identifier("class").isidentifier()
    assert task_identifier("").isidentifier()
