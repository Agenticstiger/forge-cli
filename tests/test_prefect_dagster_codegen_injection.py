"""Regression tests: untrusted contract values must not become code in the
generated Prefect flow / Dagster pipeline files.

These six emitters are the siblings of the Airflow generators pinned by
``tests/test_airflow_codegen_injection.py``. They were missed by the #215
hardening pass and by #630, and carried **zero** calls to the shared
``codegen_utils`` escapers.

They are a more severe sink than the Airflow ones. An Airflow payload runs
when the scheduler parses the DAG; here the splices land inside *module-level*
``@flow`` / ``@task`` / ``@job`` decorators, so the payload runs on any plain
``import`` of the generated file — ``prefect deploy``, a Prefect worker,
``dagster dev``, or a developer opening the file in a REPL.

Three distinct channels are pinned, because closing only the first leaves the
others open:

1. **Quote break-out** — the classic. Closed by ``py_str_literal`` (``repr``).
2. **Brace / f-string** — these emitters write generated lines that keep an
   ``f`` prefix (e.g. ``logger.info(f"Executing: {action}")``). A ``{`` in a
   contract value then becomes an *expression evaluated at task run*.
   ``repr()`` escapes quotes and backslashes but **not** braces, so
   ``py_str_literal`` alone does not close this one.
3. **Identifier position** — a ``taskId`` becoming a generated ``def`` name.

Assertions are on the parsed AST, never on generated bytes, so a formatter
cannot make them flaky — and a formatter is not a safety layer: injected
Python formats perfectly well.
"""

from __future__ import annotations

import ast

import pytest

# Quote break-out: close the literal, run a statement, reopen.
POC_SQUOTE = "x'; import os; os.system('touch /tmp/PWNED')\ny='"
POC_DQUOTE = 'x"; import os; os.system("touch /tmp/PWNED")\ny="'
# Triple-quote break-out, for docstring and triple-quoted sinks.
POC_TRIPLE = 'SELECT 1"""\nimport os; os.system("touch /tmp/PWNED")\nx="""'
# Brace channel: harmless inside a plain string, live code inside an f-string.
POC_BRACE = "value{__import__('os').system('touch /tmp/PWNED')}tail"
# Identifier position: a taskId that would become `def ...` in the output.
POC_IDENT = "t_evil\nimport os; os.system('touch /tmp/PWNED')\nx = "
# Ordinary, benign, and still fatal before the fix.
BENIGN_APOSTROPHE = "SELECT * FROM t WHERE c = 'a'"

_DANGEROUS_CALLS = {"system", "popen", "exec", "eval", "__import__", "spawn", "Popen", "getcwd"}
_DANGEROUS_MODULES = {"os", "subprocess", "sys", "shutil", "socket"}


def assert_inert(code: str) -> ast.Module:
    """Parse ``code`` and assert it contains no executable injected construct.

    Mechanism-agnostic: it does not care *how* the emitter escaped, only that
    the payload survives as inert data rather than as an AST node that runs.
    """
    tree = ast.parse(code)  # SyntaxError here means a payload broke the file
    offenders = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            name = getattr(node.func, "id", None) or getattr(node.func, "attr", None)
            if name in _DANGEROUS_CALLS:
                offenders.append(f"call:{name}")
        if isinstance(node, ast.Import):
            offenders.extend(
                f"import:{a.name}" for a in node.names if a.name.split(".")[0] in _DANGEROUS_MODULES
            )
        if (
            isinstance(node, ast.ImportFrom)
            and (node.module or "").split(".")[0] in _DANGEROUS_MODULES
        ):
            offenders.append(f"from:{node.module}")
    assert not offenders, f"code injection: generated file executes {offenders}\n---\n{code}"
    return tree


def assert_no_live_fstring_payload(code: str) -> None:
    """Assert no generated f-string evaluates a contract-derived expression.

    This is the channel ``repr()`` does not close. An emitted
    ``logger.info(f"Executing: {action}")`` turns any ``{`` in ``action`` into
    a live expression. We assert that every f-string in the generated file has
    only *simple* interpolations — names and attribute/subscript chains the
    emitter itself wrote — never a call.
    """
    tree = ast.parse(code)
    bad = []
    for node in ast.walk(tree):
        if isinstance(node, ast.JoinedStr):
            for part in node.values:
                if not isinstance(part, ast.FormattedValue):
                    continue
                for sub in ast.walk(part.value):
                    if isinstance(sub, ast.Call):
                        fn = getattr(sub.func, "id", None) or getattr(sub.func, "attr", None)
                        bad.append(f"line {getattr(node, 'lineno', '?')}: call {fn} in f-string")
    assert not bad, f"live expression injected via f-string brace channel: {bad}\n---\n{code}"


def assert_payload_is_inert_data(code: str, payload: str) -> None:
    """Escaping, not stripping: the payload must survive as readable data."""
    tree = ast.parse(code)
    literals = [
        n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)
    ]
    assert any(
        payload in lit for lit in literals
    ), "payload was mangled or dropped rather than escaped — escaping must preserve the value"


