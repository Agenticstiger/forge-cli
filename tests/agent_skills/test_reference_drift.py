"""The generated parts of the skills match their sources, so no skill can go stale.

``scripts/gen_agent_skill_references.py`` renders the contract cheat sheet from the
stable bundled schema, the error-code table from ``_error_catalog`` and the composition
table from ``PRODUCT_TYPES``. A schema promotion, a new enum value or a new error code
changes what it renders; this test then fails until someone runs the generator.
"""

from __future__ import annotations

import importlib.util
import shutil
from pathlib import Path

import pytest

from fluid_build.schema_manager import FluidSchemaManager

REPO_ROOT = Path(__file__).resolve().parents[2]
_SCRIPT = REPO_ROOT / "scripts" / "gen_agent_skill_references.py"
_spec = importlib.util.spec_from_file_location("gen_agent_skill_references", _SCRIPT)
assert _spec and _spec.loader
gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen)


def test_generated_references_are_current() -> None:
    problems = gen.check()
    assert not problems, "\n".join(problems) + f"\nRun: python {gen.GENERATOR}"


def test_every_output_carries_its_marker() -> None:
    outputs = gen.expected_outputs()
    assert len(outputs) >= 3, sorted(outputs)
    for path, text in outputs.items():
        if path.name == "SKILL.md":
            assert "<!-- BEGIN GENERATED " in text, path
        else:
            assert text.startswith("<!-- GENERATED by "), path


def test_the_sheet_reads_the_stable_schema_not_a_preview() -> None:
    sheet = next(t for p, t in gen.whole_files().items() if p.name == "contract-schema.md")
    stable = FluidSchemaManager.latest_bundled_version()
    assert stable not in FluidSchemaManager.PREVIEW_VERSIONS
    assert f"(schema {stable})" in sheet
    for preview in FluidSchemaManager.PREVIEW_VERSIONS:
        assert f"fluid-schema-{preview}.json" not in sheet


def test_the_sheet_carries_the_values_the_pilot_got_wrong() -> None:
    """No DuckDB format exists; quality types and library metrics are listed."""
    sheet = next(t for p, t in gen.whole_files().items() if p.name == "contract-schema.md")
    assert "`duckdb" not in sheet.split("binding.format")[1].split("\n")[0]
    for value in ("`library`", "`sql`", "`custom`", "`duplicateValues`", "`uniqueness`"):
        assert value in sheet, value


def test_a_hand_edit_is_caught(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    skills = tmp_path / "skills"
    shutil.copytree(gen.SKILLS_DIR, skills)
    monkeypatch.setattr(gen, "SKILLS_DIR", skills)
    sheet = skills / "authoring-fluid-contracts" / "references" / "contract-schema.md"
    sheet.write_text(sheet.read_text(encoding="utf-8").replace("`parquet`", "`duckdb`"))
    problems = gen.check()
    assert len(problems) == 1 and "contract-schema.md" in problems[0]


def test_a_schema_the_generator_cannot_read_is_an_error() -> None:
    schema = {"$defs": {}, "properties": {}, "required": []}
    with pytest.raises(gen.DriftError):
        gen.render_contract_schema(schema, "0.0.0", {"$defs": {}})


def test_an_unknown_generated_block_is_an_error() -> None:
    text = "<!-- BEGIN GENERATED no-such-block -->\n<!-- END GENERATED no-such-block -->\n"
    with pytest.raises(gen.DriftError):
        gen.fill_blocks(text)
