"""Slice 7 tests: CI header injection + ci-state.json across all providers.

Every generated CI file carries a provider-native comment header
(``#`` for the six YAML providers, ``//`` for Jenkinsfile) that names
the generator, timestamp, command, and a sha256 prefix.  After
successful generation, ``.fluid/ci-state.json`` records the inputs and
per-file sha256 so cross-machine drift detection can work.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from fluid_build.cli.artifact_ci_state import (
    build_ci_state_payload,
    write_ci_state,
)
from fluid_build.cli.artifact_paths import (
    ENVELOPE_SCHEMA_VERSION,
    product_ci_state_path,
)
from fluid_build.cli.pipeline_generator import (
    _comment_prefix_for,
    _render_header,
    build_pipeline_config,
    write_pipeline_files,
)
from fluid_build.forge.core.pipeline_templates import PipelineTemplateGenerator


class TestCommentPrefix:
    """_comment_prefix_for must pick the right comment syntax per file."""

    def test_yaml_files_use_hash(self):
        assert _comment_prefix_for("foo.yml") == "#"
        assert _comment_prefix_for("foo.yaml") == "#"
        assert _comment_prefix_for("bar/baz.yml") == "#"
        assert _comment_prefix_for(".github/workflows/fluid.yml") == "#"
        assert _comment_prefix_for(".circleci/config.yml") == "#"
        assert _comment_prefix_for("tekton/pipeline.yaml") == "#"

    def test_jenkinsfile_uses_double_slash(self):
        assert _comment_prefix_for("Jenkinsfile") == "//"
        assert _comment_prefix_for("subdir/Jenkinsfile") == "//"

    def test_unknown_falls_back_to_hash(self):
        """Defaulting to `#` covers every config format we might add later."""
        assert _comment_prefix_for("some-file.conf") == "#"
        assert _comment_prefix_for("Dockerfile") == "#"


class TestRenderHeader:
    def test_contains_generator_timestamp_command_and_schema(self):
        header = _render_header(
            filename=".github/workflows/fluid.yml",
            command="fluid forge --ci github_actions",
            tool_version="0.7.9",
            generated_at="2026-04-11T14:22:18Z",
        )
        lines = header.splitlines()
        assert "Generated by fluid-cli v0.7.9" in lines[0]
        assert "2026-04-11T14:22:18Z" in lines[0]
        assert "fluid forge --ci github_actions" in lines[1]
        # Schema line is always last
        assert lines[-1].strip().endswith("fluid.ci/v1")

    def test_yaml_header_starts_with_hash(self):
        header = _render_header(
            filename="test.yml",
            command="fluid forge --ci gitlab_ci",
            tool_version="0.7.9",
        )
        for line in header.splitlines():
            assert line.startswith("#")

    def test_jenkinsfile_header_starts_with_double_slash(self):
        header = _render_header(
            filename="Jenkinsfile",
            command="fluid forge --ci jenkins",
            tool_version="0.7.9",
        )
        for line in header.splitlines():
            assert line.startswith("//")

    def test_sha256_prefix_is_included_when_given(self):
        header = _render_header(
            filename="test.yml",
            command="fluid forge",
            tool_version="0.7.9",
            sha256_prefix="deadbeef1234",
        )
        assert "deadbeef1234" in header


@pytest.mark.parametrize(
    "provider,expected_comment",
    [
        ("github_actions", "#"),
        ("gitlab_ci", "#"),
        ("jenkins", "//"),
    ],
)
class TestWritePipelineFilesWithHeader:
    def test_generated_files_carry_header(
        self,
        provider: str,
        expected_comment: str,
        tmp_path: Path,
    ):
        config = build_pipeline_config(provider=provider, complexity="standard")
        files = PipelineTemplateGenerator().generate_pipeline(config)

        written = write_pipeline_files(
            files,
            tmp_path,
            command=f"fluid forge --ci {provider}",
            tool_version="0.7.9",
        )
        assert written, f"no files written for {provider}"

        for path in written:
            first_line = path.read_text().splitlines()[0]
            assert first_line.startswith(
                f"{expected_comment} Generated by fluid-cli"
            ), f"{provider} header wrong: {first_line!r}"

    def test_preserves_original_body_after_header(
        self,
        provider: str,
        expected_comment: str,
        tmp_path: Path,
    ):
        config = build_pipeline_config(provider=provider, complexity="standard")
        files = PipelineTemplateGenerator().generate_pipeline(config)

        # Capture the original (unheaded) content so we can assert the body survives
        originals = {name: content for name, content in files.items()}

        written = write_pipeline_files(
            files,
            tmp_path,
            command=f"fluid forge --ci {provider}",
            tool_version="0.7.9",
        )

        for path in written:
            on_disk = path.read_text()
            # The original content must appear after the header
            rel = str(path.relative_to(tmp_path))
            assert originals[rel] in on_disk, f"{provider} ({rel}): body not preserved"


class TestWritePipelineFilesHeaderOptOut:
    def test_inject_header_false_produces_clean_output(self, tmp_path: Path):
        config = build_pipeline_config(provider="gitlab_ci", complexity="basic")
        files = PipelineTemplateGenerator().generate_pipeline(config)

        written = write_pipeline_files(
            files,
            tmp_path,
            command="fluid forge",
            tool_version="0.7.9",
            inject_header=False,
        )
