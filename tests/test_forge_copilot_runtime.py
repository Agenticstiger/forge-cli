class TestResolveLlmConfig:
    def test_cli_overrides_env_for_provider_model_and_endpoint(self):
        args = SimpleNamespace(
            llm_provider="gemini",
            llm_model="gemini-2.5-pro",
            llm_endpoint="https://gateway.example.test/v1/generate",
        )

        config = resolve_llm_config(
            args,
            environ={
                "FLUID_LLM_PROVIDER": "openai",
                "FLUID_LLM_MODEL": "gpt-4o-mini",
                "FLUID_LLM_ENDPOINT": "https://api.openai.com/v1/chat/completions",
                "FLUID_LLM_API_KEY": "generic-key",
                "GEMINI_API_KEY": "gemini-key",
            },
        )

        assert config.provider == "gemini"
        assert config.model == "gemini-2.5-pro"
        assert config.endpoint == "https://gateway.example.test/v1/generate"
        assert config.api_key == "generic-key"

    def test_prefers_generic_api_key_over_provider_specific_key(self):
        args = SimpleNamespace(llm_provider="openai", llm_model=None, llm_endpoint=None)

