def _minimal_contract(provider: str = "local", engine: str = "sql") -> dict:
    properties = {"sql": "SELECT 1 AS id"}
    build = {
        "id": "main_build",
        "pattern": "embedded-logic",
        "engine": engine,
        "properties": properties,
        "execution": {
            "trigger": {"type": "manual", "iterations": 1},
            "runtime": {"platform": provider, "resources": {"cpu": "1", "memory": "2Gi"}},
        },
    }
    if engine == "python":
        build["properties"] = {"model": "src.main:build"}
        build["repository"] = "src/main.py"

    return {
        "fluidVersion": "0.7.2",
        "kind": "DataProduct",
        "id": "generated.test",
        "name": "Test Product",
        "description": "Generated by unit tests",
        "domain": "analytics",
        "metadata": {
            "layer": "Bronze",
            "owner": {"team": "data-team", "email": "data-team@example.com"},
        },
        "builds": [build],
        "exposes": [
            {
                "exposeId": "test_output",
                "kind": "table",
                "binding": {
                    "platform": provider,
                    "format": "csv",
                    "location": {"path": "runtime/out/test_output.csv"},
                },
                "contract": {"schema": [{"name": "id", "type": "integer", "required": True}]},
                "semantics": {
                    "name": "Test Output",
                    "description": "Semantic model for test output.",
                    "entities": [{"name": "id", "type": "primary"}],
                    "measures": [
                        {
                            "name": "id_count",
                            "agg": "count",
                            "expr": "id",
                            "description": "Count of id records.",
                        }
                    ],
                    "dimensions": [{"name": "id", "type": "categorical"}],
                    "metrics": [
                        {
                            "name": "id_count_metric",
                            "type": "simple",
                            "measure": "id_count",
                            "description": "Metric for id count.",
                        }
                    ],
                },
            }
        ],
    }


