# Argparse registration — --mesh-hub is wired into the CLI
# -----------------------------------------------------------------------------


class TestGenerateSpeedTransformationArgparse:
    def test_mesh_hub_flag_registered(self):
        """``fluid generate speed-transformation --mesh-hub my_hub``
        parses cleanly + surfaces on the Namespace."""
        import argparse

        from fluid_build.cli import generate_speed_transformation

        parser = argparse.ArgumentParser()
        sp = parser.add_subparsers(dest="generate_sub")
        generate_speed_transformation.register_subcommand(sp)
        ns = parser.parse_args(
            [
                "speed-transformation",
                "--mesh-hub",
                "my_data_hub",
            ]
        )
        assert ns.mesh_hub == "my_data_hub"

    def test_mesh_hub_default_none(self):
        """Default of None means no mesh_hub annotation (Option 1
        automatic-only path). Operators who want the hub opt in."""
        import argparse

        from fluid_build.cli import generate_speed_transformation

        parser = argparse.ArgumentParser()
        sp = parser.add_subparsers(dest="generate_sub")
        generate_speed_transformation.register_subcommand(sp)
        ns = parser.parse_args(["speed-transformation"])
        assert ns.mesh_hub is None
