"""A model's SQL is dbt Jinja on purpose: only its placeholders are rewritten.

``{{ ref(...) }}``, ``{{ source(...) }}``, ``{% set %}`` and comments in a build's SQL must
reach the model file as written, with ``{{ env.X }}``, ``${X}`` and ``$X`` rewritten to
``{{ env_var('X') }}``. The expected files below are what forge-cli 0.32.0 wrote for the
same input, on each path that writes model SQL (embedded logic, multi-stage, AI intent).
A YAML value from a contract still becomes a literal (``_normalize_placeholder``).
"""

from __future__ import annotations

from typing import Any, Dict

import jinja2
import pytest

from fluid_build.engines.base import TransformationIntent
from fluid_build.engines.dbt.models import generate_models
from fluid_build.engines.dbt.sources import _normalize_placeholder

pytestmark = pytest.mark.unit

_HEADER = (
    "-- Generated by fluid generate — do not edit manually.\n"
    "-- Regenerate with: fluid generate\n\n"
)

#: SQL in, model body out (forge-cli 0.32.0's output).
CASES = [
    (
        "select id from {{ ref('upstream') }}",
        "select id from {{ ref('upstream') }}",
    ),
    (
        "select id from {{ ref('upstream') }} where d = '{{ env.RUN_DATE }}'",
        "select id from {{ ref('upstream') }} where d = '{{ env_var('RUN_DATE') }}'",
    ),
    (
        "select * from {{ source('raw', 'orders') }} where region = '${REGION}' "
        "and t = '{{ env_var(\"X\", 'd') }}'",
        "select * from {{ source('raw', 'orders') }} where region = '{{ env_var('REGION') }}' "
        "and t = '{{ env_var(\"X\", 'd') }}'",
    ),
    (
        "{% set n = 3 %}select {{ n }} as n, $AMOUNT as a from {{ ref('b') }} -- {# note #}",
        "{% set n = 3 %}select {{ n }} as n, {{ env_var('AMOUNT') }} as a from {{ ref('b') }} "
        "-- {# note #}",
    ),
]

CONTRACT: Dict[str, Any] = {
    "fluidVersion": "0.7.6",
    "kind": "DataProduct",
    "id": "p",
    "name": "p",
    "exposes": [
        {
            "exposeId": "orders",
            "kind": "table",
            "contract": {"schema": [{"name": "id", "type": "string"}]},
        }
    ],
}


def _model(body: str) -> str:
    return f"{_HEADER}{{{{ config(materialized='table') }}}}\n\n{body}\n"


@pytest.mark.parametrize("sql,body", CASES)
def test_embedded_logic_sql_is_written_as_dbt_jinja(sql: str, body: str) -> None:
    build = {"id": "m", "pattern": "embedded-logic", "properties": {"sql": sql}}
    assert generate_models(CONTRACT, build) == {"models/marts/m.sql": _model(body)}


@pytest.mark.parametrize("sql,body", CASES)
def test_multi_stage_sql_is_written_as_dbt_jinja(sql: str, body: str) -> None:
    stage = {"name": "s1", "properties": {"sql": sql}, "outputs": ["orders"]}
    build = {"id": "m", "pattern": "multi-stage", "properties": {"stages": [stage]}}
    assert generate_models(CONTRACT, build) == {"models/marts/orders.sql": _model(body)}


@pytest.mark.parametrize("sql,body", CASES)
def test_ai_intent_sql_is_written_as_dbt_jinja(sql: str, body: str) -> None:
    intent = TransformationIntent(stages=[{"name": "orders", "sql": sql}])
    files = generate_models(CONTRACT, {"id": "m"}, transformation_intent=intent)
    assert files == {"models/marts/orders.sql": _model(body)}


def test_a_yaml_value_from_a_contract_stays_text() -> None:
    hostile = _normalize_placeholder("db{{ run_query('drop table t') }}")
    assert hostile.startswith('{{ "db')
    assert jinja2.Environment().from_string(hostile).render() == "db{{ run_query('drop table t') }}"
