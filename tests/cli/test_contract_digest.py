"""`fluid contract digest` — the producer for consumes[].upstreamDigest.

0.7.6 made ``upstreamDigest`` REQUIRED whenever ``upstreamWorkspace`` is
set (via ``dependentRequired``), and shipped no way to obtain the value:
``compute_contract_digest`` was reachable only from inside the federation
fetcher. The schema demanded a number nobody could produce.

The test that matters here is the round-trip — that what this command
prints is byte-identical to what ``fluid apply``'s federation gate
computes for the same upstream. A digest command that produced a
*different* digest would be worse than none, because the pin would look
authoritative and fail every apply.
"""

from __future__ import annotations

import json
from pathlib import Path
from unittest.mock import patch

import pytest
import yaml

pytestmark = pytest.mark.unit


UPSTREAM = {
    "fluidVersion": "0.7.6",
    "kind": "DataProduct",
    "id": "telco.orders",
    "name": "Telco Orders",
    "domain": "sales",
    "metadata": {"layer": "Bronze", "owner": {"team": "telco", "email": "t@example.com"}},
    "exposes": [
        {
            "exposeId": "orders",
            "kind": "table",
            "version": "1.0.0",
            "binding": {
                "platform": "local",
                "format": "parquet",
                "location": {"database": "bronze", "table": "orders"},
            },
            "contract": {"schema": [{"name": "id", "type": "integer", "required": True}]},
        }
    ],
}


def _run(args_list, tmp_path):
    """Drive the real CLI parser, not the handler directly."""
    from fluid_build.cli import build_parser

    parser = build_parser()
    args = parser.parse_args(args_list)
    import logging

    return args.func(args, logging.getLogger("test"))


@pytest.fixture
def upstream_file(tmp_path: Path) -> Path:
    p = tmp_path / "upstream.fluid.yaml"
    p.write_text(yaml.safe_dump(UPSTREAM, sort_keys=True), encoding="utf-8")
    return p


class TestDigestMatchesTheFederationGate:
    def test_printed_digest_equals_what_the_federation_fetcher_computes(
        self, upstream_file, capsys
    ):
        """The round-trip. If these ever diverge the pin is useless."""
        rc = _run(["contract", "digest", str(upstream_file)], upstream_file.parent)
        printed = capsys.readouterr().out.strip().splitlines()[-1]
        assert rc == 0

        from fluid_build.forge.federation import (
            FederatedWorkspace,
            _ClonedContract,
            _fetch_digest_via_git,
        )

        ws = FederatedWorkspace(
            id="telco", kind="git_registry", endpoint="https://git.example.invalid/telco"
        )
        with patch(
            "fluid_build.forge.federation._git_contract_file",
            return_value=_ClonedContract(upstream_file, upstream_file.parent),
        ):
            fetched = _fetch_digest_via_git(ws, "telco.orders", "1")

        assert printed == fetched, (
            "the digest this command prints must be the one `fluid apply` compares "
            f"against; got {printed!r} vs {fetched!r}"
        )

    def test_digest_is_stable_across_reformatting(self, upstream_file, tmp_path, capsys):
        """The property federation depends on.

        Peers format the same contract differently -- key order, indent,
        quoting, comments. If the digest moved with formatting, every
        upstream `yamlfmt` run would page the downstream team.
        """
        _run(["contract", "digest", str(upstream_file)], tmp_path)
        first = capsys.readouterr().out.strip().splitlines()[-1]

        hostile = tmp_path / "reformatted.yaml"
        hostile.write_text(
            "# regenerated by a peer's formatter\n"
            + yaml.safe_dump(UPSTREAM, sort_keys=False, indent=4),
            encoding="utf-8",
        )
        _run(["contract", "digest", str(hostile)], tmp_path)
        second = capsys.readouterr().out.strip().splitlines()[-1]

        assert first == second, "formatting-only change must not move the digest"

    def test_a_real_content_change_moves_the_digest(self, upstream_file, tmp_path, capsys):
        """The converse -- otherwise the pin would detect nothing."""
        _run(["contract", "digest", str(upstream_file)], tmp_path)
        before = capsys.readouterr().out.strip().splitlines()[-1]

        changed = json.loads(json.dumps(UPSTREAM))
        changed["exposes"][0]["contract"]["schema"].append(
            {"name": "customer_id", "type": "string"}
        )
        other = tmp_path / "changed.yaml"
        other.write_text(yaml.safe_dump(changed, sort_keys=True), encoding="utf-8")
        _run(["contract", "digest", str(other)], tmp_path)
        after = capsys.readouterr().out.strip().splitlines()[-1]

        assert before != after


class TestOutputShape:
    def test_bare_form_is_pipeable(self, upstream_file, capsys):
        """Exactly one line, the digest, nothing decorative -- it is meant
        to be pasted or piped straight into a contract."""
        _run(["contract", "digest", str(upstream_file)], upstream_file.parent)
        out = capsys.readouterr().out.strip()
        assert out.startswith("sha256:")
        assert len(out.split("\n")) == 1
        assert len(out) == len("sha256:") + 64

    def test_json_form_parses(self, upstream_file, capsys):
        _run(["contract", "digest", str(upstream_file), "--json"], upstream_file.parent)
        payload = json.loads(capsys.readouterr().out.strip())
        assert payload["digest"].startswith("sha256:")
        assert payload["path"].endswith("upstream.fluid.yaml")

    def test_the_digest_satisfies_the_schema_pattern(self, upstream_file, capsys):
        """What it prints must be accepted by the field it exists to fill."""
        import re

        from fluid_build.schema_manager import SchemaManager

        _run(["contract", "digest", str(upstream_file)], upstream_file.parent)
        digest = capsys.readouterr().out.strip()

        schema = SchemaManager().get_schema("0.7.6")
        pattern = schema["$defs"]["consumeRef"]["properties"]["upstreamDigest"]["pattern"]
        assert re.match(pattern, digest), f"{digest!r} does not match {pattern!r}"


class TestFailureModes:
    def test_missing_file_is_a_typed_error(self, tmp_path):
        from fluid_build.cli._common import CLIError

        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(tmp_path / "nope.yaml")], tmp_path)
        assert exc.value.event == "digest_contract_not_found"

    @pytest.mark.parametrize(
        "body",
        ["", "   \n\n", "# only a comment\n", "{}\n"],
        ids=["empty", "whitespace", "comments-only", "empty-mapping"],
    )
    def test_an_empty_contract_is_refused_rather_than_digested(self, tmp_path, body):
        """A digest of nothing is the most dangerous output this can produce.

        `yq -o=yaml '.' upstream > upstream.yaml` truncates the file to
        zero bytes the moment yq fails, and anything coercing the parse
        with `or {}` would then print sha256:44136fa3... -- a confident,
        schema-valid pin for a file with nothing in it. It matches the
        `^sha256:[0-9a-f]{64}$` pattern, so `fluid validate` accepts it,
        and every later apply compares against a digest that can never
        match the real upstream.
        """
        from fluid_build.cli._common import CLIError

        bad = tmp_path / "truncated.yaml"
        bad.write_text(body, encoding="utf-8")
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(bad)], tmp_path)
        assert exc.value.event == "digest_contract_empty"

    def test_an_alias_bomb_is_refused(self, tmp_path):
        """This command is pointed at UPSTREAM contracts -- vendored or
        freshly cloned -- so it parses input we do not control. It uses
        the same guarded loader as the federation gate whose digest it
        mirrors, rather than a bare `yaml.safe_load`."""
        from fluid_build.cli._common import CLIError

        bomb = tmp_path / "bomb.yaml"
        bomb.write_text(
            "a: &a [1,1,1,1,1,1,1,1,1]\n"
            "b: &b [*a,*a,*a,*a,*a,*a,*a,*a,*a]\n"
            "c: &c [*b,*b,*b,*b,*b,*b,*b,*b,*b]\n"
            "d: &d [*c,*c,*c,*c,*c,*c,*c,*c,*c]\n"
            "e: &e [*d,*d,*d,*d,*d,*d,*d,*d,*d]\n"
            "f: &f [*e,*e,*e,*e,*e,*e,*e,*e,*e]\n"
            "g: [*f,*f,*f,*f,*f,*f,*f,*f,*f]\n",  # >50 aliases: over the cap
            encoding="utf-8",
        )
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(bomb)], tmp_path)
        assert exc.value.event in {"digest_contract_unsafe", "digest_contract_unreadable"}

    def test_a_non_mapping_document_is_rejected(self, tmp_path):
        from fluid_build.cli._common import CLIError

        bad = tmp_path / "list.yaml"
        bad.write_text("- just\n- a\n- list\n", encoding="utf-8")
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(bad)], tmp_path)
        assert exc.value.event == "digest_contract_not_a_mapping"


# ── $ref fragments: the digest is of the contract as deployed ──────────────


def _write_split(root: Path, *, fragment_dir: str = "fragments", ext: str = "yaml") -> Path:
    """UPSTREAM with its one expose kept in a fragment, under ``root``."""
    expose = UPSTREAM["exposes"][0]
    frag = root / fragment_dir / f"orders.{ext}"
    frag.parent.mkdir(parents=True, exist_ok=True)
    frag.write_text(yaml.safe_dump(expose, sort_keys=True), encoding="utf-8")
    contract = {**UPSTREAM, "exposes": [{"$ref": f"./{fragment_dir}/orders.{ext}"}]}
    path = root / "contract.fluid.yaml"
    path.write_text(yaml.safe_dump(contract, sort_keys=True), encoding="utf-8")
    return path


def _digest(path: Path, capsys) -> str:
    _run(["contract", "digest", str(path)], path.parent)
    return capsys.readouterr().out.strip().splitlines()[-1]


class TestDigestCoversFragments:
    """``fluid split`` moves parts of a contract into ``$ref`` files. The digest
    used to hash the root alone, so an edit to a fragment left a downstream
    ``upstreamDigest`` pin green while the deployed contract had changed."""

    def test_an_edit_to_a_fragment_moves_the_digest(self, tmp_path, capsys):
        path = _write_split(tmp_path)
        before = _digest(path, capsys)

        fragment = tmp_path / "fragments" / "orders.yaml"
        fragment.write_text(fragment.read_text().replace("integer", "bigint"), encoding="utf-8")

        assert _digest(path, capsys) != before

    def test_a_split_contract_and_its_flat_twin_have_one_digest(
        self, tmp_path, upstream_file, capsys
    ):
        split = _write_split(tmp_path / "split")
        assert _digest(split, capsys) == _digest(upstream_file, capsys)

    def test_the_digest_does_not_depend_on_where_the_fragments_are_kept(self, tmp_path, capsys):
        one = _write_split(tmp_path / "one", fragment_dir="fragments")
        other = _write_split(tmp_path / "other", fragment_dir="parts/exposes", ext="yml")
        assert _digest(one, capsys) == _digest(other, capsys)

    def test_a_ref_that_cannot_be_resolved_is_an_error_not_a_digest_of_the_root(self, tmp_path):
        from fluid_build.cli._common import CLIError

        path = _write_split(tmp_path)
        (tmp_path / "fragments" / "orders.yaml").unlink()
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(path)], tmp_path)
        assert exc.value.event == "digest_contract_unresolvable"
        assert "fragments/orders.yaml" in str(exc.value.context["error"])

    def test_a_ref_that_loops_is_an_error(self, tmp_path):
        from fluid_build.cli._common import CLIError

        (tmp_path / "a.yaml").write_text("x: {$ref: ./b.yaml}\n", encoding="utf-8")
        (tmp_path / "b.yaml").write_text("y: {$ref: ./a.yaml}\n", encoding="utf-8")
        path = tmp_path / "contract.fluid.yaml"
        path.write_text("id: loop\nname: Loop\nz: {$ref: ./a.yaml}\n", encoding="utf-8")
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(path)], tmp_path)
        assert exc.value.event == "digest_contract_unresolvable"
        assert "ircular" in str(exc.value.context["error"])

    def test_a_ref_outside_the_contracts_tree_is_refused(self, tmp_path):
        from fluid_build.cli._common import CLIError

        (tmp_path / "outside.yaml").write_text("secret: s\n", encoding="utf-8")
        product = tmp_path / "product"
        product.mkdir()
        path = product / "contract.fluid.yaml"
        path.write_text("id: p\nname: P\nx: {$ref: ../outside.yaml}\n", encoding="utf-8")
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(path)], tmp_path)
        assert exc.value.event == "digest_contract_unresolvable"

    def test_a_remote_ref_is_never_fetched(self, tmp_path):
        from fluid_build.cli._common import CLIError

        path = tmp_path / "contract.fluid.yaml"
        path.write_text(
            'id: p\nname: P\nx: {$ref: "https://example.invalid/frag.yaml"}\n', encoding="utf-8"
        )
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(path)], tmp_path)
        assert exc.value.event == "digest_contract_unresolvable"

    def test_a_key_written_twice_in_a_fragment_is_refused(self, tmp_path):
        from fluid_build.cli._common import CLIError

        path = _write_split(tmp_path)
        fragment = tmp_path / "fragments" / "orders.yaml"
        fragment.write_text(fragment.read_text() + "kind: view\n", encoding="utf-8")
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(path)], tmp_path)
        assert exc.value.event == "digest_contract_unresolvable"
        assert "duplicate key" in str(exc.value.context["error"])

    def test_a_key_written_twice_in_the_root_is_refused(self, tmp_path):
        from fluid_build.cli._common import CLIError

        path = tmp_path / "contract.fluid.yaml"
        path.write_text("id: p\nname: P\nname: Q\n", encoding="utf-8")
        with pytest.raises(CLIError) as exc:
            _run(["contract", "digest", str(path)], tmp_path)
        assert exc.value.event == "digest_contract_unreadable"
        assert "duplicate key" in str(exc.value.context["error"])

    def test_an_env_placeholder_is_digested_as_written(self, tmp_path, monkeypatch, capsys):
        """The digest is of the contract, not of an operator's environment."""
        path = tmp_path / "contract.fluid.yaml"
        path.write_text("id: p\nname: P\nbucket: '{{ env.UPSTREAM_BUCKET }}'\n", encoding="utf-8")
        monkeypatch.delenv("UPSTREAM_BUCKET", raising=False)
        unset = _digest(path, capsys)
        monkeypatch.setenv("UPSTREAM_BUCKET", "somewhere")
        assert _digest(path, capsys) == unset

    def test_the_json_form_names_the_digest_of_a_split_contract(self, tmp_path, capsys):
        path = _write_split(tmp_path)
        _run(["contract", "digest", str(path), "--json"], tmp_path)
        out = json.loads(capsys.readouterr().out)
        assert out["digest"] == _digest(path, capsys)
